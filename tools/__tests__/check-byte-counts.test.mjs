import assert from 'node:assert/strict';
import { describe, test } from 'node:test';

import { ALLOWED, countsOf, problemsOf, sourcesOf } from '../check-byte-counts.mjs';

const TS = 'implementations/typescript/src/transport/shared/new-file.ts';
const CS = 'implementations/dotnet/src/Bead.Core/NewFile.cs';
const RS = 'implementations/rust/crates/bead/src/broker/new_file.rs';

describe('countsOf', () => {
  test('finds a TypeScript count interpolated before bytes', () => {
    const text = 'a();\nconst reason = `past maximumOutboxBytes, ${String(bound)} bytes`;\n';

    assert.deepEqual(countsOf(text, TS), [{ line: 2, expression: 'String(bound)' }]);
  });

  test('finds a C# count interpolated before bytes, and leaves an empty property pattern', () => {
    const text =
      'var reason = $"past maximumOutboxBytes, {_options.MaximumOutboxBytes} bytes";\n' +
      'var carries = carried is { } bytes && Carries(bytes);';

    assert.deepEqual(countsOf(text, CS), [{ line: 1, expression: '_options.MaximumOutboxBytes' }]);
  });

  test('finds a Rust count before bytes, named or positional, and a rate', () => {
    const text = [
      'format!("past maximumHeldEnvelopeBytes, {bound} bytes")',
      '"slower than minimumBodyBytesPerSecond, {} bytes a second",',
    ].join('\n');

    assert.deepEqual(countsOf(text, RS), [
      { line: 1, expression: 'bound' },
      { line: 2, expression: '' },
    ]);
  });

  test('leaves a count written through the helper, a comment and a generated file', () => {
    assert.deepEqual(countsOf('const reason = `past it, ${byteCountOf(bound)}`;', TS), []);
    assert.deepEqual(countsOf('// an envelope past its bound, {N} bytes', RS), []);
    assert.deepEqual(countsOf(' * messages of {@link LARGEST} bytes', TS), []);
    assert.deepEqual(
      countsOf('// @generated by protoc\nconst m = `must be ${String(n)} bytes`;', TS),
      []
    );
  });
});

describe('problemsOf', () => {
  test('fails a count not allowed, naming its file and line', () => {
    const problems = problemsOf([RS], () => {
      return 'let why = format!("{bound} bytes");';
    });

    assert.equal(problems.length, 1);
    assert.match(
      problems[0],
      /^implementations\/rust\/crates\/bead\/src\/broker\/new_file\.rs:1: /
    );
  });

  test('passes an allowed constant, and fails an allowed one gone', () => {
    const [path] = Object.keys(ALLOWED);
    const allowed = ALLOWED[path];
    const kept = allowed
      .map((expression) => {
        return `const x = \`\${${expression}} bytes\`;`;
      })
      .join('\n');

    assert.deepEqual(
      problemsOf([path], () => {
        return kept;
      }),
      []
    );
    assert.equal(
      problemsOf([path], () => {
        return '';
      }).length,
      allowed.length
    );
  });
});

describe('sourcesOf', () => {
  test('reads each side’s sources and leaves its tests, the DevTools extension and the demo', () => {
    assert.deepEqual(
      sourcesOf([
        TS,
        CS,
        RS,
        'implementations/typescript/src/transport/shared/__tests__/errors.test.ts',
        'implementations/dotnet/tests/Bead.Core.Tests/FailureExceptionTests.cs',
        'implementations/rust/crates/bead/src/broker/tests.rs',
        'implementations/rust/crates/bead/src/broker/tests/memory.rs',
        'implementations/typescript/devtools/src/panel.ts',
        'implementations/rust/fuzz/fuzz_targets/mqtt_packets.rs',
      ]),
      [TS, CS, RS]
    );
  });
});
