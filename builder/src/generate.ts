// types

/** A file `generate` writes: where, its text, and what it is written from. */
export interface IPlannedFile {
  readonly path: string;
  readonly content: string;
  /** Its source, as its header names it, or the blueprint's source for the blueprint. */
  readonly source: string;
}

/** What `generate --check` finds of one file: where, at which line when it differs, and what. */
export interface IFileDifference {
  readonly path: string;
  readonly line?: number;
  readonly message: string;
}

/** What `generate` gives: the files it writes, and those of its kinds it takes out. */
export interface IPlan {
  readonly files: readonly IPlannedFile[];
  readonly stale: readonly string[];
}

// constants

/** Where `generate` writes the editor's copy of Bead's options, beside `beadc.yaml`. */
export const EDITOR_COPY = '.beadc/include';

/** The folders the walk of an output's folder never enters: a build's, and a package manager's. */
export const UNWALKED: ReadonlySet<string> = new Set(['bin', 'obj', 'node_modules']);

// what a TypeScript output's folder holds of beadc's: its services, and its messages when it writes them
const SERVICES = /_bead\.ts$/u;
const MESSAGES = /_pb\.ts$/u;

// a C# file, and the first line of a file beadc's targets write
const CSHARP = /\.cs$/u;
const BEADC_HEADER = '// @generated by beadc ';

// the source each generator's header names: beadc's, protoc-gen-es's
const BEADC_SOURCE = /^\/\/ @generated by beadc \S+ from (.+): \S+, spec \S+\.$/mu;
const PROTOC_GEN_ES_SOURCE = /^\/\/ @generated from file (\S+)/mu;

// the namespace protoc's C# generator writes a file's types in
const PROTOC_CSHARP_NAMESPACE = /^namespace (\S+) \{$/mu;

// helpers

// a path as `beadc.yaml`'s folder sees it, with slashes
const slashed = (from: string, path: string): string => {
  return relative(from, path).split(sep).join('/');
};

// what a header names as each file's source
const sourcesOf = (config: IConfig, checked: IChecked): SourceNames => {
  const { source } = config;

  if ('blueprint' in source) {
    return { blueprint: slashed(config.folder, source.blueprint) };
  }

  return {
    proto: new Map(
      (checked.blueprint?.proto?.files ?? []).flatMap((file) => {
        const path = pathOnDisk(file.path, source.proto);

        return path === undefined ? [] : [[file.path, slashed(config.folder, path)] as const];
      })
    ),
  };
};

// every file under `folder`, by its full path, never inside a folder of UNWALKED, in their names'
// order; none when it is no folder
const filesUnder = (folder: string): string[] => {
  if (!existsSync(folder)) {
    return [];
  }

  // in their names' order, whatever order the system lists them in
  const entries = readdirSync(folder, { withFileTypes: true }).toSorted((a, b) => {
    return a.name < b.name ? -1 : Number(a.name > b.name);
  });

  return entries.flatMap((entry) => {
    const path = join(folder, entry.name);

    if (entry.isDirectory()) {
      return UNWALKED.has(entry.name) ? [] : filesUnder(path);
    }

    return entry.isFile() ? [path] : [];
  });
};

// the source a generated file's header names, or none it names
const sourceOf = (content: string): string | undefined => {
  return [BEADC_SOURCE, PROTOC_CSHARP_SOURCE, PROTOC_GEN_ES_SOURCE]
    .map((pattern) => {
      return pattern.exec(content)?.[1];
    })
    .find((found) => {
      return found !== undefined;
    });
};

// one output's files, under its folder
const outputFilesOf = (output: Output, input: ITargetInput): readonly IGeneratedFile[] => {
  const messages = input.set !== undefined && output.messages === Messages.GENERATE;

  if (output.language === 'csharp') {
    return [
      ...(input.set === undefined || !messages
        ? []
        : generateCSharpMessages(input.set, { blueprint: input.blueprint })),
      ...csharpTarget.generate(input, {
        ...(output.namespace === undefined ? {} : { namespace: output.namespace }),
        messages: output.messages,
      }),
    ];
  }

  const messagesOut =
    output.messagesOut === undefined ? '' : slashed(output.out, output.messagesOut);

  return [
    ...(input.set === undefined || !messages
      ? []
      : generateMessages(input.set, {
          blueprint: input.blueprint,
          importExtension: output.importExtension,
        })),
    ...typescriptTarget.generate(input, {
      importExtension: output.importExtension,
      runtime: output.runtime,
      messages: output.messages,
      ...(messagesOut === '' ? {} : { messagesOut }),
    }),
  ];
};

// whether `path`, a file of `output`'s folder, is of a kind beadc writes there: in TypeScript by its
// suffix; in C# by its first line, beadc's header, or protoc's, at the path protoc gives its source
const isBeadcs = (
  path: string,
  details: { readonly output: Output; readonly messages: boolean }
) => {
  const { output, messages } = details;

  if (output.language === 'typescript') {
    return SERVICES.test(path) || (messages && MESSAGES.test(path));
  }

  if (!CSHARP.test(path)) {
    return false;
  }

  const content = readFileSync(path, 'utf8').replaceAll('\r\n', '\n');

  if (content.startsWith(BEADC_HEADER)) {
    return true;
  }

  const source = PROTOC_CSHARP_SOURCE.exec(content)?.[1];

  if (!messages || !content.startsWith(PROTOC_CSHARP_HEADER) || source === undefined) {
    return false;
  }

  const namespace = PROTOC_CSHARP_NAMESPACE.exec(content)?.[1] ?? '';

  return slashed(output.out, path) === csharpPathOf(source, namespace);
};

// the files of `files` at one path, as a system that folds case compares paths: the first two
const samePathOf = (
  files: readonly IPlannedFile[]
): readonly [IPlannedFile, IPlannedFile] | undefined => {
  const seen = new Map<string, IPlannedFile>();

  for (const file of files) {
    const key = file.path.toLowerCase();
    const first = seen.get(key);

    if (first !== undefined) {
      return [first, file];
    }

    seen.set(key, file);
  }

  return undefined;
};

// the first line `actual` and `expected` differ at, from 1
const firstDifferenceOf = (actual: string, expected: string): number => {
  const actualLines = actual.split('\n');
  const expectedLines = expected.split('\n');
  const at = expectedLines.findIndex((line, index) => {
    return line !== actualLines[index];
  });

  return (at === -1 ? expectedLines.length : at) + 1;
};

// writes `content` beside `path` first, then moves it over: a failure never shortens the file
const writeWhole = (path: string, content: string): void => {
  const temporary = `${path}.tmp`;

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(temporary, content);
  renameSync(temporary, path);
};

// definition

/**
 * What `generate` writes for `config`, from `checked`, its source checked without an error: the
 * blueprint for a `.proto` source that names one, then each output's files; and the files of its
 * kinds the outputs' folders hold that it would not write. Throws an {@link InputError} for a source
 * it cannot generate from, for a file it would write outside its output's folder, for two files it
 * would write at one path, and for protoc's refusal.
 */
export const planOf = (config: IConfig, checked: IChecked): IPlan => {
  const { blueprint } = checked;

  if (blueprint === undefined) {
    throw new InputError('generate runs on a source check takes');
  }

  if (blueprint.services.some(bindsMessages) && checked.set === undefined) {
    throw new InputError(
      "a blueprint's proto bindings name messages only its .proto declares: name the .proto roots as the source"
    );
  }

  if (config.outputs === undefined && config.blueprint === undefined) {
    throw new InputError('beadc.yaml names no output: outputs, each a language and its folder');
  }

  const sources = sourcesOf(config, checked);
  const input: ITargetInput = {
    blueprint,
    ...(checked.set === undefined ? {} : { set: checked.set }),
    sources,
  };
  const configSource =
    'blueprint' in config.source
      ? slashed(config.folder, config.source.blueprint)
      : config.source.proto
          .map((root) => {
            return slashed(config.folder, root);
          })
          .join(', ');
  const files: IPlannedFile[] =
    config.blueprint === undefined
      ? []
      : [{ path: config.blueprint, content: formOf(blueprint), source: configSource }];
  const stale: string[] = [];

  for (const output of config.outputs ?? []) {
    const messages = input.set !== undefined && output.messages === Messages.GENERATE;
    const written = outputFilesOf(output, input).map((file) => {
      const path = join(output.out, ...file.name.split('/'));
      const source = sourceOf(file.content);

      // ! a name a blueprint gives, its `proto.file`, may climb out of the output: refused, as
      // protoc refuses a plugin's relative name, since nothing else holds a file under its folder
      if (!isInside(output.out, { target: path })) {
        throw new InputError(
          `generate would write ${slashed(config.folder, path)}, outside its output ${slashed(config.folder, output.out)}: a service's proto.file in the blueprint names a path that climbs out of it; name one under it, without ..`
        );
      }

      return {
        path,
        content: file.content,
        source:
          source === undefined
            ? slashed(config.folder, path)
            : (('proto' in sources ? sources.proto.get(source) : undefined) ?? source),
      };
    });
    const paths = new Set(
      written.map((file) => {
        return file.path;
      })
    );

    files.push(...written);
    stale.push(
      ...filesUnder(output.out).filter((path) => {
        return !paths.has(path) && isBeadcs(path, { output, messages });
      })
    );
  }

  const same = samePathOf(files);

  if (same !== undefined) {
    const [first, second] = same;

    throw new InputError(
      `generate would write ${slashed(config.folder, first.path)} from ${first.source} and ${slashed(config.folder, second.path)} from ${second.source}, one file where a system folds case: rename one of their sources, or give their outputs folders of their own`
    );
  }

  return { files, stale };
};

/** What differs between `plan` and the files on disk: a file off, missing, or left over. */
export const differencesOf = (plan: IPlan): IFileDifference[] => {
  const differences: IFileDifference[] = [];

  for (const file of plan.files) {
    if (!existsSync(file.path)) {
      differences.push({ path: file.path, message: 'no such file; beadc generate writes it' });
      continue;
    }

    const actual = readFileSync(file.path, 'utf8').replaceAll('\r\n', '\n');

    if (actual !== file.content) {
      const line = firstDifferenceOf(actual, file.content);

      differences.push({
        path: file.path,
        line,
        message: `line ${String(line)} differs from what beadc generate writes`,
      });
    }
  }

  for (const path of plan.stale) {
    differences.push({
      path,
      message: 'beadc generate writes no such file from this source; it takes it out',
    });
  }

  return differences;
};

/**
 * Writes the editor's copy of Bead's options into `folder`, under {@link EDITOR_COPY}, by its
 * content: a copy of the file would carry its mode, which an image built from a Windows checkout
 * gives as 0755.
 */
export const writeEditorCopy = (folder: string): void => {
  const copy = join(folder, ...EDITOR_COPY.split('/'), ...OPTIONS_FILE.split('/'));

  mkdirSync(dirname(copy), { recursive: true });
  writeFileSync(copy, readFileSync(join(OPTIONS_ROOT, ...OPTIONS_FILE.split('/'))));
};

/**
 * Writes `plan` for `config`: each file whose text differs, whole, then moved over; each file left
 * over taken out; and, for a `.proto` source, the editor's copy of Bead's options beside
 * `beadc.yaml`.
 */
export const writePlan = (plan: IPlan, config: IConfig): void => {
  for (const file of plan.files) {
    if (!existsSync(file.path) || readFileSync(file.path, 'utf8') !== file.content) {
      writeWhole(file.path, file.content);
    }
  }

  for (const path of plan.stale) {
    rmSync(path);
  }

  if ('proto' in config.source) {
    writeEditorCopy(config.folder);
  }
};
