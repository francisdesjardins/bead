import { readFileSync } from 'node:fs';

import { expect, test } from '@playwright/test';

import type { IBlueprint } from '../../model/blueprint.ts';
import { beadcVersion, protocGenEsVersion, specVersion } from '../../version.ts';
import { headerOf, sourceNameOf } from '../target.ts';

const INTEROP = new URL('../../../../spec/interop-blueprint.json', import.meta.url);

// the first line tools/release.mjs moves to a release's versions
const RELEASED =
  /^\/\/ @generated by beadc \d+\.\d+\.\d+ from [^:]+: bead-blueprint\/\d+, spec \d+\.\d+\.\d+\.$/u;

const interop = (): IBlueprint => {
  return JSON.parse(readFileSync(INTEROP, 'utf8')) as IBlueprint;
};

test("the header names beadc's version, the source, the format and the spec's, then a blank line", () => {
  const header = headerOf(interop(), { source: 'spec/interop-blueprint.json' });

  expect(header).toBe(
    [
      `// @generated by beadc ${beadcVersion()} from spec/interop-blueprint.json: bead-blueprint/1, spec ${specVersion()}.`,
      '// Do not edit: regenerate with beadc.',
      '',
      '',
    ].join('\n')
  );
  expect(header.split('\n')[0]).toMatch(RELEASED);
});

test('the header names protoc-gen-es and the oldest @bufbuild/protobuf its output runs on, where messages are generated', () => {
  expect(headerOf(interop(), { source: 'x.proto', messages: true }).split('\n')).toEqual([
    `// @generated by beadc ${beadcVersion()} from x.proto: bead-blueprint/1, spec ${specVersion()}.`,
    '// Do not edit: regenerate with beadc.',
    `// Messages: protoc-gen-es ${protocGenEsVersion()}, for @bufbuild/protobuf 2.13.0 or later.`,
    '',
    '',
  ]);
});

test("a header's source: the blueprint, or a .proto file by its path on disk, else its import path", () => {
  const proto = { proto: new Map([['bead/x/v1/x.proto', 'proto/bead/x/v1/x.proto']]) };

  expect(sourceNameOf({ blueprint: 'spec/interop-blueprint.json' }, undefined)).toBe(
    'spec/interop-blueprint.json'
  );
  expect(sourceNameOf(proto, 'bead/x/v1/x.proto')).toBe('proto/bead/x/v1/x.proto');
  expect(sourceNameOf(proto, 'bead/y/v1/y.proto')).toBe('bead/y/v1/y.proto');
});
