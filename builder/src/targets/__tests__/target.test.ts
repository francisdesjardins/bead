import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { expect, test } from '@playwright/test';

import { checkRoots } from '../../check.ts';
import type { IBlueprint } from '../../model/blueprint.ts';
import { protocPin } from '../../protoc.ts';
import { beadcVersion, PROTOBUF_FLOOR, protocGenEsVersion, specVersion } from '../../version.ts';
import { csharpTarget, GENERATED_MARKER } from '../csharp/csharp.ts';
import {
  headerOf,
  type IGeneratedFile,
  type ITargetInput,
  Messages,
  sourceNameOf,
} from '../target.ts';
import { DEFAULT_RUNTIME } from '../typescript/options.ts';
import { typescriptTarget } from '../typescript/typescript.ts';

const INTEROP = new URL('../../../../spec/interop-blueprint.json', import.meta.url);
const MESSAGES = fileURLToPath(new URL('../../../test/messages/', import.meta.url));

// the first line tools/release.mjs moves to a release's versions
const RELEASED =
  /^\/\/ @generated by beadc \d+\.\d+\.\d+ from [^:]+: bead-blueprint\/\d+, spec \d+\.\d+\.\d+\.$/u;

const interop = (): IBlueprint => {
  return JSON.parse(readFileSync(INTEROP, 'utf8')) as IBlueprint;
};

// the messages fixture, each file named x.proto in its header
const messagesInput = (): ITargetInput => {
  const checked = checkRoots([MESSAGES]);

  if (checked.blueprint === undefined || checked.set === undefined) {
    throw new Error('the messages fixture gives a blueprint');
  }

  return { blueprint: checked.blueprint, set: checked.set, sources: { blueprint: 'x.proto' } };
};

test("the header names beadc's version, the source, the format and the spec's, then a blank line", () => {
  const header = headerOf(interop(), { source: 'spec/interop-blueprint.json' });

  expect(header).toBe(
    [
      `// @generated by beadc ${beadcVersion()} from spec/interop-blueprint.json: bead-blueprint/1, spec ${specVersion()}.`,
      '// Do not edit: regenerate with beadc.',
      '',
      '',
    ].join('\n')
  );
  expect(header.split('\n')[0]).toMatch(RELEASED);
});

test("the header names the messages' generator and the oldest runtime its output runs on, where messages are generated", () => {
  const input = messagesInput();
  const first = `// @generated by beadc ${beadcVersion()} from x.proto: bead-blueprint/1, spec ${input.blueprint.specVersion}.`;
  const { version, googleProtobuf } = protocPin();
  const headOf = (files: readonly IGeneratedFile[]): string[] => {
    return (files[0]?.content ?? '').split('\n').slice(0, 5);
  };

  expect(
    headOf(
      typescriptTarget.generate(input, {
        importExtension: 'ts',
        runtime: DEFAULT_RUNTIME,
        messages: Messages.GENERATE,
      })
    )
  ).toEqual([
    first,
    '// Do not edit: regenerate with beadc.',
    `// Messages: protoc-gen-es ${protocGenEsVersion()}, for @bufbuild/protobuf ${PROTOBUF_FLOOR} or later.`,
    '',
    expect.stringMatching(/^import /u),
  ]);
  expect(headOf(csharpTarget.generate(input, { messages: Messages.GENERATE }))).toEqual([
    first,
    '// Do not edit: regenerate with beadc.',
    `// Messages: protoc ${version}, for Google.Protobuf ${googleProtobuf} or later.`,
    GENERATED_MARKER,
    '',
  ]);
  expect(
    headerOf(input.blueprint, {
      source: 'x.proto',
      messages: 'a 1.0, for b 2.0 or later',
      marker: '// mark',
    }).split('\n')
  ).toEqual([
    first,
    '// Do not edit: regenerate with beadc.',
    '// Messages: a 1.0, for b 2.0 or later.',
    '// mark',
    '',
    '',
  ]);
});

test("a header's source: the blueprint, or a .proto file by its path on disk, else its import path", () => {
  const proto = { proto: new Map([['bead/x/v1/x.proto', 'proto/bead/x/v1/x.proto']]) };

  expect(sourceNameOf({ blueprint: 'spec/interop-blueprint.json' }, undefined)).toBe(
    'spec/interop-blueprint.json'
  );
  expect(sourceNameOf(proto, 'bead/x/v1/x.proto')).toBe('proto/bead/x/v1/x.proto');
  expect(sourceNameOf(proto, 'bead/y/v1/y.proto')).toBe('bead/y/v1/y.proto');
});
