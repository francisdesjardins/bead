// a fixture's root through check, as generate reads a .proto source, the header naming each file
// by its path from builder/
const fixtureInput = (root: string, files?: readonly string[]): ITargetInput => {
  const checked = checkRoots([root], files === undefined ? {} : { files });

  expect(checked.diagnostics).toEqual([]);

  if (checked.blueprint === undefined || checked.set === undefined) {
    throw new Error(`${root}: no blueprint`);
  }

  return {
    blueprint: checked.blueprint,
    set: checked.set,
    sources: {
      proto: new Map(
        (checked.blueprint.proto?.files ?? []).map((file) => {
          return [file.path, relative(BUILDER, join(root, file.path)).split(sep).join('/')];
        })
      ),
    },
  };
};

const contentOf = (files: readonly IGeneratedFile[], name: string): string => {
  const file = files.find((each) => {
    return each.name === name;
  });

  if (file === undefined) {
    throw new Error(`${name}: not written`);
  }

  return file.content;
};

// a golden's header with today's versions: a release moves beadc's and the spec's, never a golden
const today = (text: string, specVersion: string): string => {
  const header = HEADER.exec(text);

  return header === null
    ? text
    : `// @generated by beadc ${beadcVersion()} from ${String(header[1])}: ${String(header[2])}, spec ${specVersion}.\n${text.slice(header[0].length)}`;
};

const filesUnder = (folder: string): string[] => {
  return readdirSync(folder, { recursive: true, withFileTypes: true })
    .filter((entry) => {
      return entry.isFile();
    })
    .map((entry) => {
      return relative(folder, join(entry.parentPath, entry.name)).split(sep).join('/');
    });
};

test("writes the comments fixture's and the messages fixture's goldens byte for byte, today's versions in their header", () => {
  const inputs = [fixtureInput(FIXTURES, [COMMENTS_PROTO]), fixtureInput(MESSAGES)];
  // protoc's own files where the pinned protoc runs; beadc's header names the pin, so its own
  // files need none
  const protoc = hasPinnedProtoc() || process.env['BEADC_PROTOC_REQUIRED'] === '1';
  const written = inputs.flatMap((input) => {
    return [
      ...(protoc && input.set !== undefined
        ? generateCSharpMessages(input.set, { blueprint: input.blueprint })
        : []),
      ...csharpTarget.generate(input, DEFAULTS),
    ].map((file) => {
      return { ...file, specVersion: input.blueprint.specVersion };
    });
  });

  if (!protoc) {
    test.info().annotations.push({
      type: 'protoc',
      description: `no protoc ${protocPin().version}: its goldens, Messages.cs and Options.cs, left uncompared`,
    });
  }

  if (process.env['BEADC_WRITE_GOLDEN'] === '1') {
    for (const file of written) {
      mkdirSync(dirname(join(GOLDEN, file.name)), { recursive: true });
      writeFileSync(join(GOLDEN, file.name), file.content);
    }
  }

  expect(
    written
      .map((file) => {
        return file.name;
      })
      .sort()
  ).toEqual(
    filesUnder(GOLDEN)
      .filter((name) => {
        return (
          name.endsWith('.cs') &&
          !name.startsWith(HTTP_GOLDEN) &&
          (protoc || name.endsWith('Bead.cs'))
        );
      })
      .sort()
  );

  for (const file of written) {
    expect(file.content, file.name).toBe(
      today(readFileSync(join(GOLDEN, file.name), 'utf8'), file.specVersion)
    );
  }
});

