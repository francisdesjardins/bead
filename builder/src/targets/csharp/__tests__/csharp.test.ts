const BUILDER = fileURLToPath(new URL('../../../../', import.meta.url));
const INTEROP = new URL('../../../../../spec/interop-blueprint.json', import.meta.url);
const GOLDEN = fileURLToPath(new URL('../../../../test/golden/csharp/', import.meta.url));
const EDITORCONFIG = new URL(
  '../../../../../implementations/dotnet/.editorconfig',
  import.meta.url
);
const FIXTURES = fileURLToPath(new URL('../../../../test/fixtures/', import.meta.url));
const MESSAGES = fileURLToPath(new URL('../../../../test/messages/', import.meta.url));
const COMMENTS_PROTO = 'bead/comments/v1/comments.proto';
const MESSAGES_PROTO = 'bead/messages/v1/messages.proto';

// what the root's beadc.yaml asks of the C# side's interop
const INTEROP_OPTIONS: ICSharpOptions = { namespace: 'Bead.Interop', messages: Messages.GENERATE };

// an output's defaults, for a .proto source, as beadc.yaml's are when it names none
const DEFAULTS: ICSharpOptions = { messages: Messages.GENERATE };

// beadc's header, its versions apart
const HEADER = /^\/\/ @generated by beadc [^ ]+ from (.+): ([^ ]+), spec [^ ]+\.\n/u;

// a type of the runtime, of .NET or of Google.Protobuf, named without `global::`
const UNQUALIFIED = /(?<!global::|[\w.])(?:Bead|System|Google)\.[A-Z]/u;

const interop = (): IBlueprint => {
  return JSON.parse(readFileSync(INTEROP, 'utf8')) as IBlueprint;
};

const interopInput = (blueprint: IBlueprint = interop()): ITargetInput => {
  return { blueprint, sources: { blueprint: 'spec/interop-blueprint.json' } };
};

// a fixture's root through check, as generate reads a .proto source, the header naming each file
// by its path from builder/
const fixtureInput = (root: string, files?: readonly string[]): ITargetInput => {
  const checked = checkRoots([root], files === undefined ? {} : { files });

  expect(checked.diagnostics).toEqual([]);

  if (checked.blueprint === undefined || checked.set === undefined) {
    throw new Error(`${root}: no blueprint`);
  }

  return {
    blueprint: checked.blueprint,
    set: checked.set,
    sources: {
      proto: new Map(
        (checked.blueprint.proto?.files ?? []).map((file) => {
          return [file.path, relative(BUILDER, join(root, file.path)).split(sep).join('/')];
        })
      ),
    },
  };
};

const contentOf = (files: readonly IGeneratedFile[], name: string): string => {
  const file = files.find((each) => {
    return each.name === name;
  });

  if (file === undefined) {
    throw new Error(`${name}: not written`);
  }

  return file.content;
};

// a golden's header with today's versions: a release moves beadc's and the spec's, never a golden
const today = (text: string, specVersion: string): string => {
  const header = HEADER.exec(text);

  return header === null
    ? text
    : `// @generated by beadc ${beadcVersion()} from ${String(header[1])}: ${String(header[2])}, spec ${specVersion}.\n${text.slice(header[0].length)}`;
};

const filesUnder = (folder: string): string[] => {
  return readdirSync(folder, { recursive: true, withFileTypes: true })
    .filter((entry) => {
      return entry.isFile();
    })
    .map((entry) => {
      return relative(folder, join(entry.parentPath, entry.name)).split(sep).join('/');
    });
};

test("writes the comments fixture's and the messages fixture's goldens byte for byte, today's versions in their header", () => {
  const inputs = [fixtureInput(FIXTURES, [COMMENTS_PROTO]), fixtureInput(MESSAGES)];
  // protoc's own files where the pinned protoc runs; beadc's header names the pin, so its own
  // files need none
  const protoc = hasPinnedProtoc() || process.env['BEADC_PROTOC_REQUIRED'] === '1';
  const written = inputs.flatMap((input) => {
    return [
      ...(protoc && input.set !== undefined
        ? generateCSharpMessages(input.set, { blueprint: input.blueprint })
        : []),
      ...csharpTarget.generate(input, DEFAULTS),
    ].map((file) => {
      return { ...file, specVersion: input.blueprint.specVersion };
    });
  });

  if (!protoc) {
    test.info().annotations.push({
      type: 'protoc',
      description: `no protoc ${protocPin().version}: its goldens, Messages.cs and Options.cs, left uncompared`,
    });
  }

  if (process.env['BEADC_WRITE_GOLDEN'] === '1') {
    for (const file of written) {
      mkdirSync(dirname(join(GOLDEN, file.name)), { recursive: true });
      writeFileSync(join(GOLDEN, file.name), file.content);
    }
  }

  expect(
    written
      .map((file) => {
        return file.name;
      })
      .sort()
  ).toEqual(
    filesUnder(GOLDEN)
      .filter((name) => {
        return name.endsWith('.cs') && (protoc || name.endsWith('Bead.cs'));
      })
      .sort()
  );

  for (const file of written) {
    expect(file.content, file.name).toBe(
      today(readFileSync(join(GOLDEN, file.name), 'utf8'), file.specVersion)
    );
  }
});

test("the goldens' .editorconfig is implementations/dotnet's, byte for byte", () => {
  expect(readFileSync(join(GOLDEN, '.editorconfig'), 'utf8')).toBe(
    readFileSync(EDITORCONFIG, 'utf8')
  );
});

test("an accepted case's output differs from the interop's by its patch alone: SPEC_VERSION_NEWER's header, NOTIFICATION_RESULT's codec and the types it writes", () => {
  const accepted = blueprintCases().filter((each) => {
    return each.findings.every((finding) => {
      return RULES[finding.rule as keyof typeof RULES].severity === Severity.WARNING;
    });
  });
  const lines = contentOf(
    csharpTarget.generate(interopInput(), INTEROP_OPTIONS),
    'InteropBead.cs'
  ).split('\n');
  const differencesOf = (patched: IBlueprint): string[] => {
    const theirs = contentOf(
      csharpTarget.generate(interopInput(patched), INTEROP_OPTIONS),
      'InteropBead.cs'
    ).split('\n');

    expect(theirs).toHaveLength(lines.length);

    return theirs.filter((line, at) => {
      return line !== lines[at];
    });
  };

  expect(
    accepted.map((each) => {
      return each.rule;
    })
  ).toEqual(['NOTIFICATION_RESULT', 'SPEC_VERSION_NEWER']);

  for (const each of accepted) {
    const differences = differencesOf(applyPatch(interop(), each.patch) as IBlueprint);
    const raw = 'global::System.ReadOnlyMemory<byte>';
    const json = 'global::System.Text.Json.JsonElement';

    expect(differences, each.rule).toEqual(
      each.rule === 'SPEC_VERSION_NEWER'
        ? [
            `// @generated by beadc ${beadcVersion()} from spec/interop-blueprint.json: bead-blueprint/1, spec 99.0.0.`,
          ]
        : [
            `    public static global::Bead.RequestProcedure<InteropProcedures, ${json}, ${raw}, ${json}, InteropFailures.Ticks> Ticks { get; } = new(`,
            `        new global::Bead.ProcedureBindings<${json}, ${raw}, ${json}>`,
            '            Result = global::Bead.PayloadCodecs.Raw,',
            `    public global::System.Func<${json}, global::Bead.BoundCall<${raw}>> Ticks { get; }`,
          ]
    );
  }
});

test("writes a service a blueprint alone declares at the output's root, under its name, in the output's namespace, and one a .proto declares beside protoc's file, in its namespace's folder", () => {
  const alone = csharpTarget.generate(interopInput(), INTEROP_OPTIONS);
  const comments = csharpTarget.generate(fixtureInput(FIXTURES, [COMMENTS_PROTO]), DEFAULTS);
  const messages = csharpTarget.generate(fixtureInput(MESSAGES), DEFAULTS);

  expect(
    alone.map((file) => {
      return file.name;
    })
  ).toEqual(['InteropBead.cs']);
  expect(contentOf(alone, 'InteropBead.cs')).toContain('\nnamespace Bead.Interop;\n');
  expect(
    [...comments, ...messages].map((file) => {
      return file.name;
    })
  ).toEqual(['Bead/Comments/V1/CommentsBead.cs', 'Bead/Messages/V1/MessagesBead.cs']);
  expect(contentOf(comments, 'Bead/Comments/V1/CommentsBead.cs')).toContain(
    '\nnamespace Bead.Comments.V1;\n'
  );
});

test('writes two services of one .proto in one file, the contract with the runtime once', () => {
  const comments = fixtureInput(FIXTURES, [COMMENTS_PROTO]);
  const [service] = comments.blueprint.services;

  if (service === undefined) {
    throw new Error('the comments fixture declares a service');
  }

  const content = contentOf(
    csharpTarget.generate(
      {
        ...comments,
        blueprint: {
          ...comments.blueprint,
          services: [service, { ...service, serviceId: 3, serviceName: 'Other' }],
        },
      },
      DEFAULTS
    ),
    'Bead/Comments/V1/CommentsBead.cs'
  );

  expect(content).toContain('public sealed class CommentsServer<TData>\n');
  expect(content).toContain('public sealed class OtherServer<TData>\n');
  expect(content.match(/GeneratedCode\.SupportsVersion2;/gu)).toHaveLength(1);
  expect(content.match(/^\/\/ @generated/gmu)).toHaveLength(1);
  expect(content.match(/^namespace /gmu)).toHaveLength(1);
});

test("writes */, <, & and two paragraphs as XML documentation, a command's among them, and a character C# reads as a line's end, a lone CR among them, as its reference", () => {
  const ends = ['\r', '\u{85}', '\u{2028}', '\u{2029}'].join('');
  const blueprint = structuredClone(interop()) as unknown as {
    services: { procedures: { procedureName: string; description?: string }[] }[];
  };
  const procedures = blueprint.services[0]?.procedures ?? [];

  for (const procedure of procedures) {
    if (procedure.procedureName === 'echo') {
      procedure.description = `Ends */, holds <tag> & ${ends}, and a line\nafter it.`;
    }

    if (procedure.procedureName === 'clock') {
      procedure.description = 'The time,\nwhere its client is.\n\nA second paragraph.';
    }
  }

  const content = contentOf(
    csharpTarget.generate(interopInput(blueprint as unknown as IBlueprint), INTEROP_OPTIONS),
    'InteropBead.cs'
  );

  expect(content).toContain(
    [
      '    /// <summary>',
      '    /// Ends */, holds &lt;tag&gt; &amp; &#xD;&#x85;&#x2028;&#x2029;, and a line',
      '    /// after it. Admits every call.',
      '    /// </summary>',
    ].join('\n')
  );
  expect(content).toContain(
    [
      '    /// <summary>',
      '    /// <para>The time,',
      '    /// where its client is.</para>',
      '    /// <para>A second paragraph.</para>',
      '    /// </summary>',
      '    public required global::System.Func<',
    ].join('\n')
  );
  expect(
    content.split('\n').filter((line) => {
      return /[\r\u{85}\u{2028}\u{2029}]/u.test(line);
    })
  ).toEqual([]);
});

test('puts the header above #nullable and the namespace, <auto-generated/> its last line', () => {
  const input = fixtureInput(MESSAGES);
  const content = contentOf(
    csharpTarget.generate(input, DEFAULTS),
    'Bead/Messages/V1/MessagesBead.cs'
  );
  const { version, googleProtobuf } = protocPin();

  expect(content.split('\n').slice(0, 8)).toEqual([
    `// @generated by beadc ${beadcVersion()} from test/messages/${MESSAGES_PROTO}: bead-blueprint/1, spec ${input.blueprint.specVersion}.`,
    '// Do not edit: regenerate with beadc.',
    `// Messages: protoc ${version}, for Google.Protobuf ${googleProtobuf} or later.`,
    GENERATED_MARKER,
    '',
    '#nullable enable',
    '',
    'namespace Bead.Messages.V1;',
  ]);
});

test("qualifies every type it names from global::, so no type of the namespace takes a runtime type's place", () => {
  const blueprint = structuredClone(interop()) as unknown as {
    services: { serviceName: string }[];
  };

  (blueprint.services[0] as { serviceName: string }).serviceName = 'Service';

  const content = contentOf(
    csharpTarget.generate(interopInput(blueprint as unknown as IBlueprint), {
      namespace: 'Bead',
      messages: Messages.GENERATE,
    }),
    'ServiceBead.cs'
  );
  const code = content.split('\n').filter((line) => {
    return !line.trimStart().startsWith('//') && !line.startsWith('namespace ');
  });

  expect(content).toContain('public sealed class ServiceServer<TData>\n');
  expect(content).toContain(
    '    private readonly global::Bead.ServiceServer<ServiceProcedures, TData> _service;\n'
  );
  expect(
    code.filter((line) => {
      return UNQUALIFIED.test(line);
    })
  ).toEqual([]);
});

test("names an external output's messages by their namespace, and names no generator of them", () => {
  const content = contentOf(
    csharpTarget.generate(fixtureInput(MESSAGES), { messages: Messages.EXTERNAL }),
    'Bead/Messages/V1/MessagesBead.cs'
  );

  expect(content).toContain(
    'global::Bead.RequestProcedure<GreeterProcedures, global::Bead.Messages.V1.Greeting, global::Bead.Messages.V1.Greeting.Types.Reply, GreeterFailures.SayHello>'
  );
  expect(content).toContain('global::Google.Protobuf.WellKnownTypes.Timestamp');
  expect(content).not.toContain('// Messages:');
});
