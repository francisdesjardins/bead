// ── C# ────────────────────────────────────────────────────────────────────────

// The C# target (decision 0022): one `<File>Bead.cs` for each file a service's `proto` member names,
// whichever the source, beside the `<File>.cs` protoc writes for it, in its namespace's folder and in
// that namespace, protoc's own layout under `base_namespace=`: the set's `csharp_namespace` for a
// `.proto` source, the output's for a blueprint; or `<Name>Bead.cs` at the output's root for a
// service with no `proto` member, in the output's namespace. Each file is beadc's header, its last
// line `// <auto-generated/>`, then `#nullable enable`, which a file marked generated needs, then
// `#pragma warning disable` of the deprecations, protobuf's and Bead's, which the file names itself,
// as protoc's and gRPC's own files open, the namespace, each service, the rules of each message its
// requests' rules reach (decision 0035), and once the contract with the runtime. A message is named from its descriptor as
// protoc's C# generator names it: its file's namespace, then its enclosing messages, each followed
// by `Types`, every name qualified from `global::`. An output with `http: true` writes `BeadHttp.cs`
// besides, beside the first service's file, its route table and the document (`http.ts`, decision
// 0037).

// dependencies

import { createFileRegistry, type DescMessage, fromBinary } from '@bufbuild/protobuf';
import {
  type DescriptorProto,
  type FileDescriptorProto,
  FileDescriptorSetSchema,
} from '@bufbuild/protobuf/wkt';

import {
  type IServiceEntry,
  LEGACY_REQUIRED_FEATURE,
  VALIDATE_FEATURE,
} from '../../model/blueprint.ts';
import { judgedMessagesOf, plansOf } from '../../model/rules.ts';
import { csharpPathOf, protocPin } from '../../protoc.ts';
import { csharpNamespaceOf } from '../names.ts';
import {
  bindsMessages,
  DEPRECATION_ID,
  headerOf,
  type IGeneratedFile,
  type ITarget,
  type ITargetInput,
  Messages,
  sourceNameOf,
} from '../target.ts';
import { HTTP_FILE, printCSharpHttp } from './http.ts';
import type { ICSharpOptions } from './options.ts';
import { printService } from './templates.ts';
import { printCSharpValidators } from './validators.ts';

// constants

/** The line Roslyn reads as generated code's mark, the header's last: a consumer's analyzers skip the file. */
export const GENERATED_MARKER = '// <auto-generated/>';

// helpers

// a file's namespace, as protoc's C# generator gives it
const namespaceOf = (file: FileDescriptorProto): string => {
  return csharpNamespaceOf(file.package, file.options?.csharpNamespace);
};

// every message of the set, by its full name, as a C# type qualified from `global::`
const messageTypesOf = (files: readonly FileDescriptorProto[]): Map<string, string> => {
  const types = new Map<string, string>();
  const walk = (
    message: DescriptorProto,
    place: { readonly fullName: string; readonly csharp: string }
  ): void => {
    const fullName = place.fullName === '' ? message.name : `${place.fullName}.${message.name}`;
    const csharp = place.csharp === '' ? message.name : `${place.csharp}.${message.name}`;

    types.set(fullName, `global::${csharp}`);

    for (const nested of message.nestedType) {
      walk(nested, { fullName, csharp: `${csharp}.Types` });
    }
  };

  for (const file of files) {
    for (const message of file.messageType) {
      walk(message, { fullName: file.package, csharp: namespaceOf(file) });
    }
  }

  return types;
};

// definition

/** The C# target: a `Bead.cs` for each service's file, over the service layer. */
export const csharpTarget: ITarget<ICSharpOptions> = Object.freeze({
  name: 'csharp',
  features: new Set([LEGACY_REQUIRED_FEATURE, VALIDATE_FEATURE]),
  http: true,
  generate: (input: ITargetInput, options: ICSharpOptions): readonly IGeneratedFile[] => {
    const { blueprint } = input;
    const set =
      input.set === undefined ? undefined : fromBinary(FileDescriptorSetSchema, input.set);
    const protoFiles = new Map(
      (set?.file ?? []).map((file) => {
        return [file.name, file] as const;
      })
    );
    const types = messageTypesOf(set?.file ?? []);
    const registry = set === undefined ? undefined : createFileRegistry(set);
    const rules = judgedMessagesOf(blueprint);
    const descOf = (fullName: string): DescMessage => {
      const message = registry?.getMessage(fullName);

      if (message === undefined) {
        throw new Error(`${fullName}: no message of buf's set`);
      }

      return message;
    };
    const messageOf = (fullName: string): string => {
      const type = types.get(fullName);

      if (type === undefined) {
        throw new Error(`${fullName}: no message of buf's set`);
      }

      return type;
    };
    // a file a `.proto` file, or a service with no `proto` member: never two sources in one, so
    // `generate` sees, and refuses, two files at one path
    const files = new Map<
      string,
      { readonly name: string; readonly namespace: string; readonly services: IServiceEntry[] }
    >();

    for (const service of blueprint.services) {
      const protoFile =
        service.proto === undefined ? undefined : protoFiles.get(service.proto.file);
      const namespace = protoFile === undefined ? options.namespace : namespaceOf(protoFile);

      if (namespace === undefined) {
        throw new Error(
          `${service.serviceName}: a C# output names the namespace of a service a blueprint alone declares`
        );
      }

      const name =
        service.proto === undefined
          ? `${service.serviceName}Bead.cs`
          : csharpPathOf(service.proto.file, namespace).replace(/\.cs$/u, 'Bead.cs');
      const key = service.proto === undefined ? `${service.serviceName}.` : service.proto.file;
      const entry = files.get(key) ?? { name, namespace, services: [] };

      entry.services.push(service);
      files.set(key, entry);
    }

    const written = [...files.values()].map(({ name, namespace, services }) => {
      const [first] = services;
      const pin = protocPin();
      const header = headerOf(blueprint, {
        source: sourceNameOf(input.sources, first?.proto?.file),
        ...(options.messages === Messages.GENERATE && services.some(bindsMessages)
          ? {
              messages: `protoc ${pin.version}, for Google.Protobuf ${pin.googleProtobuf} or later`,
            }
          : {}),
        marker: GENERATED_MARKER,
      });
      const validators = printCSharpValidators(plansOf(services, rules), {
        messageOf: descOf,
        typeOf: messageOf,
      });
      const body = [
        '#nullable enable',
        // ! protoc's and gRPC's own form, in every file: a deprecated member, protobuf's or Bead's, is
        // named by the file that declares or binds it, and a compiler warning is no analyzer's, which
        // <auto-generated/> silences
        `#pragma warning disable CS0612, CS0618, ${DEPRECATION_ID} // a deprecated member, protobuf's or Bead's, is named by its own file`,
        ...(namespace === '' ? [] : ['', `namespace ${namespace};`]),
        ...services.flatMap((service) => {
          return ['', ...printService(service, { messageOf, validators: validators.classes })];
        }),
        ...validators.lines,
        '',
        '// the contract with the runtime this file needs: an older runtime lacks the constant, and fails here',
        'file static class GeneratedCodeContract',
        '{',
        '    private const bool Supported = global::Bead.GeneratedCode.SupportsVersion6;',
        '}',
        '',
      ];

      return { name, content: `${header}${body.join('\n')}` };
    });
    const [first] = blueprint.services;
    const firstFile = [...files.values()][0];

    if (options.http === undefined || first === undefined || firstFile === undefined) {
      return written;
    }

    // * the route table beside the first service's file, in its namespace
    const folder = firstFile.name.includes('/')
      ? firstFile.name.slice(0, firstFile.name.lastIndexOf('/') + 1)
      : '';
    const header = headerOf(blueprint, {
      source: sourceNameOf(input.sources, first.proto?.file),
      ...(options.messages === Messages.GENERATE && blueprint.services.some(bindsMessages)
        ? {
            messages: `protoc ${protocPin().version}, for Google.Protobuf ${protocPin().googleProtobuf} or later`,
          }
        : {}),
      marker: GENERATED_MARKER,
    });
    const namespaceOfService = (service: IServiceEntry): string => {
      const protoFile =
        service.proto === undefined ? undefined : protoFiles.get(service.proto.file);

      return protoFile === undefined ? (options.namespace ?? '') : namespaceOf(protoFile);
    };
    const lines = printCSharpHttp({
      blueprint,
      http: options.http,
      namespace: firstFile.namespace,
      namespaceOf: namespaceOfService,
      messageOf,
    });

    return [...written, { name: `${folder}${HTTP_FILE}`, content: `${header}${lines.join('\n')}` }];
  },
});
