// ── Messages ──────────────────────────────────────────────────────────────────

// The Rust messages a project's `proto` bindings name, written by Buffa's `protoc-gen-buffa`, the
// stock plugin, pinned as protoc is (decision 0051): beadc hands it a `CodeGeneratorRequest`
// itself, the protobuf plugin protocol's (`google/protobuf/compiler/plugin.proto`), and runs no
// protoc. Its set is the one beadc hands protoc for the C# target: buf's, protovalidate's options
// and `google.api.http` taken out unless the output keeps them; pruned to the files the messages
// need, so the descriptor set each package embeds holds nothing of protovalidate's or googleapis'.
// The files it generates are those that declare a message a binding names and the files they
// import, Google's well-known types and beadc's own files apart, which `buffa-types` holds or no
// message needs; its parameter is `bead_protobuf_build::config_of`'s settings, `views`,
// `reflect_mode=vtable`, `unknown_fields` and `allow_message_set`, and each repeated or map field of
// a closed enum opened, as `opened_of` computes them. The plugin writes no module root, so beadc
// writes `messages/mod.rs` itself, as `buffa-build` writes an include file (`generate_module_tree`):
// an application's build script through `config_of` over the same set writes the same files.
//
// The plugin is held to one pin, `builder/protoc-gen-buffa.json`: its version, the Buffa its code
// requires, and each release binary's sha256, which `tools/fetch-protoc-gen-buffa.mjs` checks
// before it runs one. beadc runs the plugin `BEADC_PROTOC_GEN_BUFFA` names, or `protoc-gen-buffa`
// on the path, and refuses one of another version, since another writes other code; only
// `generate` looks for it, and only when it writes a message.

