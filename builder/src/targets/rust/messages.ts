// types

/** The pin, `builder/protoc-gen-buffa.json`: the one plugin beadc runs, and what its code needs. */
export interface IBuffaPin {
  readonly version: string;
  /** The requirement of Buffa's crates its code compiles against, Cargo's, exact. */
  readonly buffa: string;
  /** Each release binary's sha256, by its platform's name in the release's: `linux-x86_64`. */
  readonly sha256: Readonly<Record<string, string>>;
}

/** The plugin beadc found: where, and the version it says it is. */
export interface IFoundPlugin {
  readonly path: string;
  readonly version: string;
}

/** What beadc hands the plugin: the files it generates, its parameter, and the pruned set. */
export interface IBuffaRequest {
  /** The files it generates, by their import paths, in the set's order. */
  readonly files: readonly string[];
  readonly parameter: string;
  /** The set it reads, a FileDescriptorSet: each file's bytes as buf's set holds them, pruned. */
  readonly set: Uint8Array;
}

// constants

/** The folder of an output that holds Buffa's tree, and the module that mounts it. */
export const MESSAGES_FOLDER = 'messages';

/** The first line of a file Buffa writes, its root's beadc writes among them. */
export const BUFFA_HEADER = '// @generated by buffa-codegen. DO NOT EDIT.';

/**
 * The settings of Buffa's generator `bead_protobuf_build::config_of` gives, as the plugin's
 * parameter names them: views, reflection by vtable, unknown fields kept, `MessageSet` allowed.
 */
export const BUFFA_SETTINGS: readonly string[] = Object.freeze([
  'views=true',
  'reflect_mode=vtable',
  'unknown_fields=true',
  'allow_message_set=true',
]);

// the lints Buffa allows on each module of its tree, `ALLOW_LINTS`, in its order
const ALLOW_LINTS = [
  'non_camel_case_types',
  'dead_code',
  'unused_imports',
  'unused_qualifications',
  'clippy::derivable_impls',
  'clippy::match_single_binding',
  'clippy::uninlined_format_args',
  'clippy::doc_lazy_continuation',
  'clippy::module_inception',
].join(', ');

// the files Buffa generates nothing for: buffa-types holds the well-known types
const WELL_KNOWN = 'google/protobuf/';

/** The module path of Google's well-known types, as Buffa maps their package by default. */
export const WELL_KNOWN_PATH = '::buffa_types::google::protobuf';

// the pin, beside the builder's sources
const PIN = new URL('../../../protoc-gen-buffa.json', import.meta.url);

// what a plugin's output may hold: the plugin protocol's limit is protoc's, far above this
const MAXIMUM_OUTPUT = 512 * 1024 * 1024;

// a script a plugin stands behind on Windows, which runs through its shell alone
const SCRIPT = /\.(?:bat|cmd)$/iu;

// helpers

let pin: IBuffaPin | undefined;

// the fix for a plugin missing or off its pin, to whoever runs beadc, in a clone or not
const fixOf = (version: string): string => {
  return `name protoc-gen-buffa ${version} by BEADC_PROTOC_GEN_BUFFA, from https://github.com/anthropics/buffa/releases/tag/v${version}, or run beadc's image, ${IMAGE}, which holds it`;
};

const pluginPath = (): string => {
  const named = process.env['BEADC_PROTOC_GEN_BUFFA'];

  return named === undefined || named === '' ? 'protoc-gen-buffa' : named;
};

// a varint, as the wire format writes one
const varintOf = (value: number): number[] => {
  const bytes: number[] = [];
  let rest = value;

  while (rest >= 0x80) {
    bytes.push((rest % 0x80) + 0x80);
    rest = Math.floor(rest / 0x80);
  }

  bytes.push(rest);

  return bytes;
};

// a length-delimited field, `number`'s, holding `payload`
const delimitedOf = (number: number, payload: Uint8Array): Uint8Array => {
  // ! a field's key is its number shifted by three, its wire type 2 below
  return new Uint8Array([...varintOf(number * 8 + 2), ...varintOf(payload.length), ...payload]);
};

const joined = (parts: readonly Uint8Array[]): Uint8Array => {
  const whole = new Uint8Array(
    parts.reduce((length, part) => {
      return length + part.length;
    }, 0)
  );
  let at = 0;

  for (const part of parts) {
    whole.set(part, at);
    at += part.length;
  }

  return whole;
};

// each file of a FileDescriptorSet, its bytes as the set holds them: its field 1, repeated
const fileBytesOf = (set: Uint8Array): Uint8Array[] => {
  const files: Uint8Array[] = [];
  let at = 0;
  const read = (): number => {
    let value = 0;
    let scale = 1;

    for (;;) {
      const byte = set[at];

      if (byte === undefined) {
        throw new Error("buf's set ends inside a varint");
      }

      at += 1;
      value += (byte % 0x80) * scale;
      scale *= 0x80;

      if (byte < 0x80) {
        return value;
      }
    }
  };

  while (at < set.length) {
    const key = read();
    const wire = key % 8;

    if (wire !== 2) {
      throw new Error(`buf's set holds a field of wire type ${String(wire)}`);
    }

    const length = read();

    if (Math.floor(key / 8) === 1) {
      files.push(set.subarray(at, at + length));
    }

    at += length;
  }

  return files;
};

// the edition a file's features start from
const editionOf = (file: FileDescriptorProto): Edition => {
  if (file.syntax === 'proto3') {
    return Edition.EDITION_PROTO3;
  }

  return file.syntax === 'editions' ? file.edition : Edition.EDITION_PROTO2;
};

// definition

/** The pin, read from `builder/protoc-gen-buffa.json` once. */
export const buffaPin = (): IBuffaPin => {
  pin ??= Object.freeze(JSON.parse(readFileSync(PIN, 'utf8')) as IBuffaPin);

  return pin;
};

/** What a header names as the messages' generator: the plugin, and the Buffa its code requires. */
export const buffaMessagesOf = (): string => {
  const { version, buffa } = buffaPin();

  return `protoc-gen-buffa ${version}, for buffa ${buffa}`;
};

/** The plugin beadc finds, `BEADC_PROTOC_GEN_BUFFA` or the path's, and its version; none when none runs. */
export const findBuffa = (): IFoundPlugin | undefined => {
  const path = pluginPath();

  const options: ExecSyncOptionsWithStringEncoding = {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
    windowsHide: true,
  };

  try {
    const said = (
      process.platform === 'win32' && SCRIPT.test(path)
        ? execSync(`"${path}" --version`, options)
        : execFileSync(path, ['--version'], options)
    ).trim();

    return { path, version: said.replace(/^protoc-gen-buffa /u, '') };
  } catch {
    return undefined;
  }
};

/**
 * The plugin beadc runs, at its pin's version. Throws an {@link InputError} with the fix for none,
 * or for one of another version, which writes other code.
 */
export const requireBuffa = (): IFoundPlugin => {
  const found = findBuffa();
  const { version } = buffaPin();

  if (found === undefined) {
    throw new InputError(
      `no protoc-gen-buffa at ${pluginPath()}, which writes the Rust messages, pinned to protoc-gen-buffa ${version}: ${fixOf(version)}; or set the output's messages to external`
    );
  }

  if (found.version !== version) {
    throw new InputError(
      `protoc-gen-buffa ${found.version} at ${found.path}, where beadc is pinned to protoc-gen-buffa ${version}, whose Rust another writes otherwise: ${fixOf(version)}`
    );
  }

  return found;
};

/**
 * The fields of `files`' messages Buffa opens, as `bead_protobuf_build::opened_of` computes them,
 * each by its path, `.package.Message.field`, in the order Buffa's pool walks them: every repeated
 * field whose item, and every map whose value, is of a closed enum, the field itself not opening it.
 */
export const openedOf = (
  descriptors: readonly FileDescriptorProto[],
  files: ReadonlySet<string>
): string[] => {
  // * each enum's own type: its features over its scope's, over its file's, over its edition's
  const closed = new Map<string, boolean>();
  const enumsOf = (
    file: FileDescriptorProto,
    scope: { readonly prefix: string; readonly closed: boolean; readonly message?: DescriptorProto }
  ): void => {
    const declared = scope.message?.enumType ?? file.enumType;

    for (const each of declared) {
      const own = each.options?.features?.enumType;

      closed.set(
        `${scope.prefix}.${each.name}`,
        own === undefined || own === FeatureSet_EnumType.ENUM_TYPE_UNKNOWN
          ? scope.closed
          : own === FeatureSet_EnumType.CLOSED
      );
    }

    for (const nested of scope.message?.nestedType ?? file.messageType) {
      const own = nested.options?.features?.enumType;

      enumsOf(file, {
        prefix: `${scope.prefix}.${nested.name}`,
        closed:
          own === undefined || own === FeatureSet_EnumType.ENUM_TYPE_UNKNOWN
            ? scope.closed
            : own === FeatureSet_EnumType.CLOSED,
        message: nested,
      });
    }
  };

  for (const file of descriptors) {
    const own = file.options?.features?.enumType;
    const byEdition = editionOf(file) === Edition.EDITION_PROTO2;

    enumsOf(file, {
      prefix: file.package === '' ? '' : `.${file.package}`,
      closed:
        own === undefined || own === FeatureSet_EnumType.ENUM_TYPE_UNKNOWN
          ? byEdition
          : own === FeatureSet_EnumType.CLOSED,
    });
  }

  const opened: string[] = [];
  const opensItself = (field: FieldDescriptorProto): boolean => {
    return field.options?.features?.enumType === FeatureSet_EnumType.OPEN;
  };
  const walk = (message: DescriptorProto, fullName: string): void => {
    const entries = new Map<string, DescriptorProto>(
      message.nestedType
        .filter((nested) => {
          return nested.options?.mapEntry === true;
        })
        .map((nested) => {
          return [`${fullName}.${nested.name}`, nested] as const;
        })
    );

    for (const field of message.field) {
      const entry = entries.get(field.typeName);
      const value = entry?.field.find((each) => {
        return each.number === 2;
      });
      const item =
        field.label === FieldDescriptorProto_Label.REPEATED &&
        entry === undefined &&
        field.type === FieldDescriptorProto_Type.ENUM
          ? field
          : undefined;
      const mapped =
        entry !== undefined && value?.type === FieldDescriptorProto_Type.ENUM ? value : undefined;
      const held = item ?? mapped;

      if (held !== undefined && !opensItself(held) && closed.get(held.typeName) === true) {
        opened.push(`${fullName}.${field.name}`);
      }
    }

    for (const nested of message.nestedType) {
      walk(nested, `${fullName}.${nested.name}`);
    }
  };

  for (const file of descriptors) {
    if (files.has(file.name)) {
      for (const message of file.messageType) {
        walk(
          message,
          file.package === '' ? `.${message.name}` : `.${file.package}.${message.name}`
        );
      }
    }
  }

  return opened;
};

/**
 * Whether `blueprint` binds a message Buffa writes: one of a file of its own, not Google's well-known
 * types, which buffa-types holds, nor beadc's own files. The output's `messages` root holds those
 * alone, under `generate` and under `external` alike.
 */
export const hasOwnMessages = (blueprint: IBlueprint): boolean => {
  return (blueprint.proto?.messages ?? []).some((message) => {
    return !message.file.startsWith(WELL_KNOWN) && !BEADC_FILES.has(message.file);
  });
};

/**
 * What beadc hands the plugin for the messages `blueprint` binds, from `given`, buf's
 * FileDescriptorSet of its `.proto` source: none when it binds none of a file of its own. The set is
 * buf's with protovalidate's options and `google.api.http` taken out, unless the output keeps them,
 * then pruned to the files those generated import, each file's bytes kept; the files generated are
 * those that declare a message bound and the files they import, but Google's well-known types and
 * beadc's own files.
 */
export const buffaRequestOf = (
  given: Uint8Array,
  options: {
    readonly blueprint: IBlueprint;
    readonly keepValidateOptions?: boolean;
    readonly keepHttpOptions?: boolean;
  }
): IBuffaRequest | undefined => {
  const validated = options.keepValidateOptions === true ? given : withoutValidateOptions(given);
  const stripped = options.keepHttpOptions === true ? validated : withoutHttpOptions(validated);
  const bytes = fileBytesOf(stripped);
  const descriptors = bytes.map((each) => {
    return fromBinary(FileDescriptorProtoSchema, each);
  });
  const dependencies = new Map(
    descriptors.map((file) => {
      return [file.name, file.dependency];
    })
  );
  const generated = new Set<string>();
  const want = (file: string): void => {
    if (file.startsWith(WELL_KNOWN) || BEADC_FILES.has(file) || generated.has(file)) {
      return;
    }

    generated.add(file);

    for (const dependency of dependencies.get(file) ?? []) {
      want(dependency);
    }
  };

  for (const message of options.blueprint.proto?.messages ?? []) {
    want(message.file);
  }

  if (generated.size === 0) {
    return undefined;
  }

  // * the set pruned to what the generated files import, so that each package's embedded set
  // holds no file its messages do not need
  const kept = new Set<string>();
  const keep = (file: string): void => {
    if (kept.has(file)) {
      return;
    }

    kept.add(file);

    for (const dependency of dependencies.get(file) ?? []) {
      keep(dependency);
    }
  };

  for (const file of generated) {
    keep(file);
  }

  const files = descriptors
    .map((file) => {
      return file.name;
    })
    .filter((name) => {
      return generated.has(name);
    });
  const set = joined(
    bytes.flatMap((each, at) => {
      return kept.has(descriptors[at]?.name ?? '') ? [delimitedOf(1, each)] : [];
    })
  );
  const prunedDescriptors = descriptors.filter((file) => {
    return kept.has(file.name);
  });
  const opened = openedOf(prunedDescriptors, generated).map((field) => {
    return `open_enums_in=${field}`;
  });

  return { files, parameter: [...BUFFA_SETTINGS, ...opened].join(','), set };
};

/**
 * The root of Buffa's tree under `messages/`, `mod.rs`, as `buffa-build` writes its include file
 * (`generate_module_tree`, relative, no inner attribute): a module a package segment, each under
 * Buffa's `#[allow]`, each package's root included where its last segment is.
 */
export const messagesRootOf = (packages: readonly string[]): string => {
  interface INode {
    files: string[];
    readonly children: Map<string, INode>;
  }

  const root: INode = { files: [], children: new Map() };

  for (const each of packages) {
    let node = root;

    for (const segment of each === '' ? [] : each.split('.')) {
      const child = node.children.get(segment) ?? { files: [], children: new Map() };

      node.children.set(segment, child);
      node = child;
    }

    node.files.push(packageToModFilename(each));
  }

  const lines = [BUFFA_HEADER, ''];
  const emit = (node: INode, depth: number): void => {
    const indent = '    '.repeat(depth);

    for (const file of node.files) {
      lines.push(`${indent}include!("${file}");`);
    }

    const children = [...node.children.entries()].toSorted(([one], [other]) => {
      return one < other ? -1 : Number(one > other);
    });

    for (const [segment, child] of children) {
      lines.push(
        `${indent}#[allow(${ALLOW_LINTS})]`,
        `${indent}pub mod ${identifierOf(segment)} {`,
        `${indent}    use super::*;`
      );
      emit(child, depth + 1);
      lines.push(`${indent}}`);
    }
  };

  emit(root, 0);

  return `${lines.join('\n')}\n`;
};

/**
 * The Rust files of the messages `blueprint` binds, from `set`, buf's FileDescriptorSet of its
 * `.proto` source, under `messages/`: Buffa's files as its plugin writes them, and their root,
 * `mod.rs`; none, and no plugin looked for, when it binds none of a file of its own. Throws an
 * {@link InputError} for no plugin, one off its pin, or the plugin's own refusal, in its words.
 */
export const generateRustMessages = (
  set: Uint8Array,
  options: {
    readonly blueprint: IBlueprint;
    readonly keepValidateOptions?: boolean;
    readonly keepHttpOptions?: boolean;
  }
): readonly IGeneratedFile[] => {
  const request = buffaRequestOf(set, options);

  if (request === undefined) {
    return [];
  }

  const plugin = requireBuffa();
  const descriptors = fileBytesOf(request.set).map((each) => {
    return fromBinary(FileDescriptorProtoSchema, each);
  });
  // * the plugin protocol's request: the files to generate, the parameter, and every file of the
  // pruned set, each the set's own bytes, so that the set Buffa embeds is the one beadc pruned
  const input = joined([
    ...request.files.map((file) => {
      return delimitedOf(1, new TextEncoder().encode(file));
    }),
    delimitedOf(2, new TextEncoder().encode(request.parameter)),
    ...fileBytesOf(request.set).map((each) => {
      return delimitedOf(15, each);
    }),
  ]);
  let output: Buffer;

  try {
    output = execFileSync(plugin.path, [], {
      input,
      maxBuffer: MAXIMUM_OUTPUT,
      stdio: ['pipe', 'pipe', 'pipe'],
      windowsHide: true,
    });
  } catch (error) {
    const { stderr } = error as { stderr?: unknown };
    const said = Buffer.isBuffer(stderr) ? stderr.toString('utf8').trim() : '';

    throw new InputError(`protoc-gen-buffa: ${said === '' ? (error as Error).message : said}`);
  }

  const response = fromBinary(CodeGeneratorResponseSchema, new Uint8Array(output));

  if (response.error !== '') {
    throw new InputError(`protoc-gen-buffa: ${response.error}`);
  }

  const packages = [
    ...new Set(
      descriptors
        .filter((file) => {
          return request.files.includes(file.name);
        })
        .map((file) => {
          return file.package;
        })
    ),
  ];

  return [
    ...response.file.map((file) => {
      return {
        name: `${MESSAGES_FOLDER}/${file.name}`,
        content: file.content.replaceAll('\r\n', '\n'),
      };
    }),
    { name: `${MESSAGES_FOLDER}/mod.rs`, content: messagesRootOf(packages) },
  ];
};
