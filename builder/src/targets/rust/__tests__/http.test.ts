import { readFileSync } from 'node:fs';

import { expect, test } from '@playwright/test';

import { InputError } from '../../../diagnostics.ts';
import type { IBlueprint } from '../../../model/blueprint.ts';
import { applyPatch } from '../../../model/__tests__/patch.ts';
import { documentOf } from '../../../openapi/document.ts';
import { type IGeneratedFile, Messages } from '../../target.ts';
import { HTTP_FILE } from '../http.ts';
import type { IRustOptions } from '../options.ts';
import { rustTarget } from '../rust.ts';

const INTEROP = new URL('../../../../../spec/interop-blueprint.json', import.meta.url);

const interop = (): IBlueprint => {
  return JSON.parse(readFileSync(INTEROP, 'utf8')) as IBlueprint;
};

const outputOf = (
  blueprint: IBlueprint,
  options: Partial<IRustOptions> = {}
): readonly IGeneratedFile[] => {
  return rustTarget.generate(
    { blueprint, sources: { blueprint: 'spec/interop-blueprint.json' } },
    {
      messages: Messages.GENERATE,
      http: { prefix: '/api', document: documentOf(blueprint) },
      ...options,
    }
  );
};

const contentOf = (files: readonly IGeneratedFile[], name: string): string => {
  const file = files.find((each) => {
    return each.name === name;
  });

  if (file === undefined) {
    throw new Error(`${name}: not written`);
  }

  return file.content;
};

const tableOf = (blueprint: IBlueprint): string => {
  return contentOf(outputOf(blueprint), HTTP_FILE);
};

test('writes bead_http.rs at the root, each procedure a client calls by its descriptor, a native payload by its encoding, its catalogue and its routes, a command never', () => {
  const written = outputOf(interop());
  const table = contentOf(written, HTTP_FILE);
  const mod = contentOf(written, 'mod.rs');

  expect(table).toMatch(/^\/\/ @generated by beadc \S+ from spec\/interop-blueprint\.json: /u);
  expect(mod).toContain('pub mod bead_http {\n    //! Its gateway');
  expect(mod).toContain('    include!("bead_http.rs");\n');
  expect(table).toContain(
    '        let interop_procedures = super::services::InteropProcedures::get()?;'
  );
  expect(table).toContain(
    [
      '    // the route of `Interop/echo`',
      '    fn route_0(procedures: &super::services::InteropProcedures) -> Result<::bead::HttpRoute, ::bead::ProgrammerError> {',
      '        ::bead::route_of(::bead::HttpRouteInit {',
      '            procedure: ::bead::ServiceProcedure::from(&procedures.echo),',
      '            request: ::bead::HttpPayload::Json,',
      '            result: ::bead::HttpPayload::Json,',
      '            notification: None,',
      '            failures: ::std::vec![super::services::InteropFailures::ON_PURPOSE, super::services::InteropFailures::REGISTERED_ALREADY],',
      '            no_side_effects: false,',
      '            routes: ::std::vec![',
      '                ::bead::HttpRouteTemplate { method: ::bead::HttpMethod::Post, template: "/api/Interop/echo".to_owned(), body: Some("*".to_owned()), response_body: None },',
      '            ],',
      '        })',
      '    }',
    ].join('\n')
  );
  expect(table).toContain('            notification: Some(::bead::HttpPayload::Json),');
  expect(table).not.toContain('procedures.clock');
  // * no message bound, no JSON form made
  expect(table).not.toContain('::bead_protobuf::');
  expect(table).toContain(
    'pub const HTTP_PROBLEM_TYPES: ::core::option::Option<&str> = ::core::option::Option::None;'
  );
  expect(table.endsWith('const _: bool = ::bead::GENERATED_CODE_SUPPORTS_VERSION_5;\n')).toBe(true);
});

test('writes a typed HTTP client on default routes, with a stream for each notifying procedure and no command', () => {
  const table = tableOf(interop());
  const json = '<::bead::JsonCodec as ::bead::PayloadCodec>::Value';

  expect(table).toContain('pub struct InteropHttpClient {');
  expect(table).toContain(
    '    pub fn new(url: &str, options: &::bead::HttpCallerOptions) -> Result<Self, ::bead::ProgrammerError> {'
  );
  expect(table).toContain('        let caller = ::bead::HttpCaller::new(url, options)?;');
  expect(table).toContain(
    `    pub fn echo(&self, request: &${json}, options: &::bead::HttpCallOptions) -> ::bead::BoxFuture<Result<${json}, ::bead::CallError>> {`
  );
  expect(table).toContain(
    '            echo: caller.requester_of(routes.at(0)?, &procedures.echo)?,'
  );
  expect(table).toContain(
    '            ticks: caller.requester_of(routes.at(8)?, procedures.ticks.descriptor())?,'
  );
  expect(table).toContain(
    '            subscribe_ticks: caller.subscriber_of(routes.at(8)?, &procedures.ticks)?,'
  );
  expect(table).toContain(
    `    pub fn subscribe_ticks(&self, request: &${json}, options: &::bead::HttpCallOptions) -> ::bead::HttpSubscription<${json}, ${json}> {`
  );
  expect(table).not.toContain('pub fn subscribe_echo');
  expect(table).not.toContain('pub fn clock');
});

test('marks HTTP client types and requesters deprecated with their definitions', () => {
  const blueprint = interop();
  const table = tableOf({
    ...blueprint,
    services: blueprint.services.map((service) => {
      return {
        ...service,
        deprecation: { message: 'Use Other.' },
        procedures: service.procedures.map((procedure) => {
          return { ...procedure, deprecation: { message: 'Call another procedure.' } };
        }),
      };
    }),
  });

  expect(table).toContain(
    [
      '#[deprecated(note = "Use Other.")]',
      '#[derive(Debug, Clone)]',
      'pub struct InteropHttpClient {',
    ].join('\n')
  );
  expect(table).toContain(
    ['    #[deprecated(note = "Call another procedure.")]', '    pub fn echo('].join('\n')
  );
  expect(table).toContain(
    ['    #[deprecated(note = "Call another procedure.")]', '    pub fn subscribe_ticks('].join(
      '\n'
    )
  );
});

test('writes an HTTP client for a service whose procedures are commands alone', () => {
  const blueprint = interop();
  const table = tableOf({
    ...blueprint,
    services: blueprint.services.map((service) => {
      return {
        ...service,
        procedures: service.procedures.filter((procedure) => {
          return procedure.procedureKind === 'command';
        }),
      };
    }),
  });

  expect(table).toContain('pub struct InteropHttpClient;');
  expect(table).toContain('        ::bead::HttpCaller::new(url, options).map(|_caller| Self)');
  expect(table).toContain('            all: ::std::vec::Vec::new(),');
  expect(table).not.toContain('requester_of(');
  expect(table).not.toContain('subscriber_of(');
});

test('writes no bead_http.rs without a gateway', () => {
  const written = rustTarget.generate(
    { blueprint: interop(), sources: { blueprint: 'spec/interop-blueprint.json' } },
    { messages: Messages.GENERATE }
  );

  expect(
    written.map((file) => {
      return file.name;
    })
  ).toEqual(['mod.rs', 'services/__buffa.rs']);
  expect(contentOf(written, 'mod.rs')).not.toContain('bead_http');
});

test('refuses an output with a gateway whose procedure renders as a method its HTTP client holds', () => {
  for (const name of ['new', 'clone', 'fmt']) {
    const named = applyPatch(interop(), [
      { op: 'replace', path: '/services/0/procedures/0/procedureName', value: name },
    ]) as IBlueprint;

    expect(() => {
      return outputOf(named);
    }).toThrow(
      new InputError(
        `the procedure Interop/${name} is the method ${name} of InteropHttpClient in Rust, which the client holds already: rename the procedure, or take it out of the output's gateway`
      )
    );
    // * without a gateway, no client holds it
    expect(
      rustTarget
        .generate(
          { blueprint: named, sources: { blueprint: 'spec/interop-blueprint.json' } },
          { messages: Messages.GENERATE }
        )
        .map((file) => {
          return file.name;
        })
    ).toEqual(['mod.rs', 'services/__buffa.rs']);
  }

  // * a command, which no HTTP client calls, takes the name
  const command = applyPatch(interop(), [
    { op: 'replace', path: '/services/0/procedures/8/procedureName', value: 'new' },
  ]) as IBlueprint;

  expect(tableOf(command)).not.toContain('pub fn new(&self');
});
