// what a golden folder holds, each file's name and its text, and the set beside a proto fixture's
interface IGolden {
  readonly folder: string;
  readonly written: readonly IGeneratedFile[];
  readonly specVersion: string;
  readonly set?: Uint8Array;
}

// writes `golden` where BEADC_WRITE_GOLDEN asks it, then holds the folder to it, byte for byte
const holdGolden = (golden: IGolden): void => {
  const folder = join(GOLDEN, golden.folder);

  if (process.env['BEADC_WRITE_GOLDEN'] === '1') {
    rmSync(folder, { recursive: true, force: true });

    for (const file of golden.written) {
      mkdirSync(dirname(join(folder, file.name)), { recursive: true });
      writeFileSync(join(folder, file.name), file.content);
    }

    if (golden.set !== undefined) {
      writeFileSync(join(folder, SET_FILE), golden.set);
    }
  }

  expect(
    golden.written
      .map((file) => {
        return file.name;
      })
      .toSorted()
  ).toEqual(
    filesUnder(folder)
      .filter((name) => {
        return name !== SET_FILE;
      })
      .toSorted()
  );

  for (const file of golden.written) {
    expect(file.content, `${golden.folder}${file.name}`).toBe(
      today(
        readFileSync(join(folder, file.name), 'utf8').replaceAll('\r\n', '\n'),
        golden.specVersion
      )
    );
  }

  if (golden.set !== undefined) {
    expect(Buffer.from(readFileSync(join(folder, SET_FILE))).equals(Buffer.from(golden.set))).toBe(
      true
    );
  }
};

test("writes the comments fixture's and the messages fixture's goldens byte for byte, today's versions in their header", () => {
  const comments = fixtureInput(FIXTURES, [COMMENTS_PROTO]);
  const messages = fixtureInput(MESSAGES, [MESSAGES_PROTO]);
  const validations = fixtureInput(MESSAGES, [RULES_PROTO]);
  // * the plugin's files where the pinned plugin runs; beadc's header names the pin, so its own
  // files need none
  const plugin = hasPinnedBuffa();

  if (!plugin) {
    test.info().annotations.push({
      type: 'protoc-gen-buffa',
      description: `no protoc-gen-buffa ${buffaPin().version}: the messages fixture's messages/ left uncompared`,
    });
  }

  holdGolden({
    folder: 'comments/',
    written: rustTarget.generate(comments, DEFAULTS),
    specVersion: comments.blueprint.specVersion,
  });

  if (messages.set === undefined || validations.set === undefined) {
    throw new Error('the messages fixture compiles to a set');
  }

  const request = buffaRequestOf(messages.set, { blueprint: messages.blueprint });
  const written = [
    ...(plugin ? generateRustMessages(messages.set, { blueprint: messages.blueprint }) : []),
    ...rustTarget.generate(messages, DEFAULTS),
  ];

  if (plugin) {
    holdGolden({
      folder: 'messages/',
      written,
      specVersion: messages.blueprint.specVersion,
      ...(request === undefined ? {} : { set: request.set }),
    });
  } else {
    // beadc's own files alone, held to the golden
    for (const file of written) {
      expect(file.content, file.name).toBe(
        today(
          readFileSync(join(GOLDEN, 'messages', file.name), 'utf8').replaceAll('\r\n', '\n'),
          messages.blueprint.specVersion
        )
      );
    }
  }

  // * the validations fixture, its messages the application's build's, from buf's set as it is
  holdGolden({
    folder: 'validations/',
    written: rustTarget.generate(validations, { messages: Messages.EXTERNAL }),
    specVersion: validations.blueprint.specVersion,
    set: validations.set,
  });
});

