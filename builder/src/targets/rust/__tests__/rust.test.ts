test("the codec a target writes is the runtime's codec of its message's schema, which holds spec 17.9 whole", () => {
  const content = contentOf(
    rustTarget.generate(fixtureInput(MESSAGES, [MESSAGES_PROTO]), DEFAULTS),
    'services/bead.messages.v1.rs'
  );
  const codecs = [...content.matchAll(/^ {16,20}(?:request|result): (.*),$/gmu)].map((match) => {
    return match[1] ?? '';
  });

  expect(codecs.length).toBeGreaterThan(0);

  // * a proto binding's codec is the runtime's of its message, nothing of its own beside it
  for (const codec of codecs) {
    expect(codec).toMatch(
      /^(?:::bead_protobuf::ProtoCodec::new\(\)\?|::bead::(?:RawCodec|TextCodec|JsonCodec))$/u
    );
  }

  expect(content).toContain(
    '::bead_protobuf::ProtoCodec<super::super::super::super::messages::bead::messages::v1::Greeting>'
  );
  // a nested message through Buffa's module, a well-known type through buffa-types
  expect(content).toContain(
    'super::super::super::super::messages::bead::messages::v1::greeting::Reply'
  );
  expect(content).toContain(
    '::bead_protobuf::ProtoCodec<::buffa_types::google::protobuf::Timestamp>'
  );
  // a file that binds no proto message names no codec of one
  expect(
    contentOf(rustTarget.generate(interopInput(), DEFAULTS), 'services/__buffa.rs')
  ).not.toContain('ProtoCodec');
});

