import { readFileSync } from 'node:fs';

import { expect, test } from '@playwright/test';

import type { IBlueprint } from '../../../model/blueprint.ts';
import { documentOf } from '../../../openapi/document.ts';
import { Messages } from '../../target.ts';
import { HTTP_FILE } from '../http.ts';
import { DEFAULT_PROTO_RUNTIME, DEFAULT_RUNTIME, type ITypeScriptOptions } from '../options.ts';
import { typescriptTarget } from '../typescript.ts';

const INTEROP = new URL('../../../../../spec/interop-blueprint.json', import.meta.url);

const interop = (): IBlueprint => {
  return JSON.parse(readFileSync(INTEROP, 'utf8')) as IBlueprint;
};

const tableOf = (blueprint: IBlueprint, options: Partial<ITypeScriptOptions> = {}): string => {
  const written = typescriptTarget.generate(
    { blueprint, sources: { blueprint: 'spec/interop-blueprint.json' } },
    {
      importExtension: 'ts',
      runtime: DEFAULT_RUNTIME,
      protoRuntime: DEFAULT_PROTO_RUNTIME,
      messages: Messages.GENERATE,
      http: {
        prefix: '/api',
        document: documentOf(blueprint),
        runtime: '@francisdesjardins/bead/transcoding',
      },
      ...options,
    }
  );
  const file = written.find((each) => {
    return each.name === HTTP_FILE;
  });

  if (file === undefined) {
    throw new Error(`${HTTP_FILE}: not written`);
  }

  return file.content;
};

test('writes bead_http.ts at the root, each procedure a client calls by its descriptor, a native payload by its encoding, its catalogue and its routes, a command never', () => {
  const table = tableOf(interop());

  expect(table).toMatch(/^\/\/ @generated by beadc \S+ from spec\/interop-blueprint\.json: /u);
  expect(table).toContain('from "@francisdesjardins/bead/transcoding";');
  expect(table).toContain('import { InteropProcedures } from "./interop_bead.ts";');
  expect(table).toContain(
    [
      '  routeOf({',
      '    procedure: InteropProcedures.echo,',
      "    request: 'json',",
      "    result: 'json',",
      '    failures: { ON_PURPOSE: 7, REGISTERED_ALREADY: 8 },',
      '    routes: [',
      "      { method: 'POST', template: '/api/Interop/echo', body: '*' },",
      '    ],',
      '  }),',
    ].join('\n')
  );
  expect(table).toContain("    notification: 'json',");
  expect(table).not.toContain('InteropProcedures.clock');
  expect(table).toContain('export const HTTP_PROBLEM_TYPES = undefined;');
  expect(table.endsWith('void GENERATED_CODE_SUPPORTS_VERSION_5;\n')).toBe(true);
});

test('writes a typed HTTP client on default routes, with a stream for each notifying procedure and no command', () => {
  const table = tableOf(interop());

  expect(table).toContain('export class InteropHttpClient {');
  expect(table).toContain('public readonly echo: IHTTPRequester<typeof HTTP_ROUTES[0]>;');
  expect(table).toContain('this.echo = httpRequesterOf(HTTP_ROUTES[0], caller);');
  expect(table).toContain('createHTTPCaller(HTTP_ROUTES, options)');
  expect(table).not.toContain('public readonly clock');
  expect(table).toContain('] as const);');
});

test('marks HTTP client types and requesters deprecated with their definitions', () => {
  const blueprint = interop();
  const table = tableOf({
    ...blueprint,
    services: blueprint.services.map((service) => {
      return {
        ...service,
        deprecation: { message: 'Use Other.' },
        procedures: service.procedures.map((procedure) => {
          return { ...procedure, deprecation: { message: 'Call another procedure.' } };
        }),
      };
    }),
  });

  expect(table).toContain('@deprecated Use Other.');
  expect(table).toContain('@deprecated Call another procedure.');
  expect(table).toContain('export class InteropHttpClient');
});

test('writes an HTTP client for a service whose procedures are commands alone', () => {
  const blueprint = interop();
  const table = tableOf({
    ...blueprint,
    services: blueprint.services.map((service) => {
      return {
        ...service,
        procedures: service.procedures.filter((procedure) => {
          return procedure.procedureKind === 'command';
        }),
      };
    }),
  });

  expect(table).toContain('export class InteropHttpClient');
  expect(table).toContain('    void caller;');
  expect(table).not.toContain('httpRequesterOf(');
});

test("writes no bead_http.ts without http, and imports a relative runtime at the output's root", () => {
  const written = typescriptTarget.generate(
    { blueprint: interop(), sources: { blueprint: 'spec/interop-blueprint.json' } },
    {
      importExtension: 'none',
      runtime: DEFAULT_RUNTIME,
      protoRuntime: DEFAULT_PROTO_RUNTIME,
      messages: Messages.GENERATE,
    }
  );

  expect(
    written.map((file) => {
      return file.name;
    })
  ).toEqual(['interop_bead.ts']);
  expect(
    tableOf(interop(), {
      importExtension: 'js',
      http: { prefix: '/api', document: '{}\n', runtime: '../runtime/transcoding' },
    })
  ).toContain('from "../runtime/transcoding.js";');
});
