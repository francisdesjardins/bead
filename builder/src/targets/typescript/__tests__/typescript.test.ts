test('marks a deprecated procedure\'s every declaration, with its message or "No replacement is named."', () => {
  const content = contentOf(
    typescriptTarget.generate(fixtureInput(MESSAGES), DEFAULTS),
    'bead/messages/v1/messages_bead.ts'
  );
  // a declaration under its doc comment's mark, at its indent: a member's, or an overload's
  const marked = (
    mark: string,
    at: { readonly declaration: string; readonly indent: string }
  ): string => {
    const { declaration, indent } = at;

    return [`${indent} * @deprecated ${mark}`, `${indent} */`, `${indent}${declaration}`].join(
      '\n'
    );
  };

  // * watch's descriptor, its requester and its resolver's overload, its message; name's
  // descriptor and its resolver's overload on the client, the default
  expect(content).toContain(
    marked('Use sayHello.', { declaration: 'watch: requestOf({', indent: '  ' })
  );
  expect(content).toContain(
    marked('Use sayHello.', { declaration: 'public readonly watch: ', indent: '  ' })
  );
  expect(content).toContain(
    marked('Use sayHello.', {
      declaration: "<Name extends 'watch'>(name: Name, callback: GreeterResolvers[Name]): void;",
      indent: '    ',
    })
  );
  expect(content).toContain(
    marked('No replacement is named.', { declaration: 'name: commandOf({', indent: '  ' })
  );
  expect(content).toContain(
    marked('No replacement is named.', {
      declaration: "<Name extends 'name'>(name: Name, callback: ",
      indent: '    ',
    })
  );
  // the notification, the command's requester, the notifier, the resolver's key and the window are
  // the layer's, mapped from the descriptor, which carries the mark to each
  expect(content.match(/@deprecated/gu)).toHaveLength(5);
});

