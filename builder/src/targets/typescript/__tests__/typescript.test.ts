import { typescriptTarget } from '../typescript.ts';

const BUILDER = fileURLToPath(new URL('../../../../', import.meta.url));
const INTEROP = new URL('../../../../../spec/interop-blueprint.json', import.meta.url);
const COMMITTED = new URL(
  '../../../../../implementations/typescript/interop/generated/interop_bead.ts',
  import.meta.url
);
const GOLDEN = fileURLToPath(new URL('../../../../test/golden/typescript/', import.meta.url));
const FIXTURES = fileURLToPath(new URL('../../../../test/fixtures/', import.meta.url));
const MESSAGES = fileURLToPath(new URL('../../../../test/messages/', import.meta.url));
// the goldens' type-checks, against @bufbuild/protobuf's pin and its floor: no output of beadc's
const GOLDEN_CONFIGS = new Set(['tsconfig.floor.json', 'tsconfig.json']);
const COMMENTS_PROTO = 'bead/comments/v1/comments.proto';
const MESSAGES_PROTO = 'bead/messages/v1/messages.proto';

// what the root's beadc.yaml asks of the interop's output
const INTEROP_OPTIONS: ITypeScriptOptions = {
  importExtension: 'none',
  runtime: '../../src/service/service',
  messages: Messages.GENERATE,
};

// an output's defaults, as beadc.yaml's are when it names none
const DEFAULTS: ITypeScriptOptions = {
  importExtension: 'ts',
  runtime: DEFAULT_RUNTIME,
  messages: Messages.GENERATE,
};

// beadc's header, its versions apart
const HEADER = /^\/\/ @generated by beadc [^ ]+ from (.+): ([^ ]+), spec [^ ]+\.\n/u;

const interop = (): IBlueprint => {
  return JSON.parse(readFileSync(INTEROP, 'utf8')) as IBlueprint;
};

const interopInput = (blueprint: IBlueprint = interop()): ITargetInput => {
  return { blueprint, sources: { blueprint: 'spec/interop-blueprint.json' } };
};

// a fixture's root through check, as generate reads a .proto source, the header naming each file
// by its path from builder/
const fixtureInput = (root: string, files?: readonly string[]): ITargetInput => {
  const checked = checkRoots([root], files === undefined ? {} : { files });

  expect(checked.diagnostics).toEqual([]);

  if (checked.blueprint === undefined || checked.set === undefined) {
    throw new Error(`${root}: no blueprint`);
  }

  return {
    blueprint: checked.blueprint,
    set: checked.set,
    sources: {
      proto: new Map(
        (checked.blueprint.proto?.files ?? []).map((file) => {
          return [file.path, relative(BUILDER, join(root, file.path)).split(sep).join('/')];
        })
      ),
    },
  };
};

// what an output holds: the messages, then the services
const outputOf = (input: ITargetInput, options: ITypeScriptOptions): readonly IGeneratedFile[] => {
  return [
    ...(input.set === undefined
      ? []
      : generateMessages(input.set, {
          blueprint: input.blueprint,
          importExtension: options.importExtension,
        })),
    ...typescriptTarget.generate(input, options),
  ];
};

const contentOf = (files: readonly IGeneratedFile[], name: string): string => {
  const file = files.find((each) => {
    return each.name === name;
  });

  if (file === undefined) {
    throw new Error(`${name}: not written`);
  }

  return file.content;
};

// a golden's header with today's versions: a release moves beadc's and the spec's, never a golden
const today = (text: string, specVersion: string): string => {
  const header = HEADER.exec(text);

  return header === null
    ? text
    : `// @generated by beadc ${beadcVersion()} from ${String(header[1])}: ${String(header[2])}, spec ${specVersion}.\n${text.slice(header[0].length)}`;
};

const filesUnder = (folder: string): string[] => {
  return readdirSync(folder, { recursive: true, withFileTypes: true })
    .filter((entry) => {
      return entry.isFile();
    })
    .map((entry) => {
      return relative(folder, join(entry.parentPath, entry.name)).split(sep).join('/');
    });
};

test("writes the comments fixture's and the messages fixture's goldens byte for byte, today's versions in their header", () => {
  const inputs = [fixtureInput(FIXTURES, [COMMENTS_PROTO]), fixtureInput(MESSAGES)];
  const written = inputs.flatMap((input) => {
    return outputOf(input, DEFAULTS).map((file) => {
      return { ...file, specVersion: input.blueprint.specVersion };
    });
  });

  if (process.env['BEADC_WRITE_GOLDEN'] === '1') {
    for (const file of written) {
      mkdirSync(dirname(join(GOLDEN, file.name)), { recursive: true });
      writeFileSync(join(GOLDEN, file.name), file.content);
    }
  }

  expect(
    written
      .map((file) => {
        return file.name;
      })
      .sort()
  ).toEqual(
    filesUnder(GOLDEN)
      .filter((name) => {
        return !GOLDEN_CONFIGS.has(name);
      })
      .sort()
  );

  for (const file of written) {
    expect(file.content, file.name).toBe(
      today(readFileSync(join(GOLDEN, file.name), 'utf8'), file.specVersion)
    );
  }
});

test("an accepted case's output differs from the interop's by its patch alone: SPEC_VERSION_NEWER's header, NOTIFICATION_RESULT's codec", () => {
  const accepted = blueprintCases().filter((each) => {
    return each.findings.every((finding) => {
      return RULES[finding.rule as keyof typeof RULES].severity === Severity.WARNING;
    });
  });
  const lines = contentOf(
    typescriptTarget.generate(interopInput(), INTEROP_OPTIONS),
    'interop_bead.ts'
  ).split('\n');
  const differencesOf = (patched: IBlueprint): string[] => {
    const theirs = contentOf(
      typescriptTarget.generate(interopInput(patched), INTEROP_OPTIONS),
      'interop_bead.ts'
    ).split('\n');

    expect(theirs).toHaveLength(lines.length);

    return theirs.filter((line, at) => {
      return line !== lines[at];
    });
  };

  expect(
    accepted.map((each) => {
      return each.rule;
    })
  ).toEqual(['NOTIFICATION_RESULT', 'SPEC_VERSION_NEWER']);

  for (const each of accepted) {
    const differences = differencesOf(applyPatch(interop(), each.patch) as IBlueprint);

    expect(differences, each.rule).toEqual(
      each.rule === 'SPEC_VERSION_NEWER'
        ? [
            `// @generated by beadc ${beadcVersion()} from spec/interop-blueprint.json: bead-blueprint/1, spec 99.0.0.`,
          ]
        : ['    result: PAYLOAD_CODECS.raw,']
    );
  }
});

test("writes a service a blueprint alone declares at the output's root, under its name, and one a .proto declares at its path, a relative runtime's import rewritten for its depth", () => {
  const alone = typescriptTarget.generate(interopInput(), INTEROP_OPTIONS);
  const comments = fixtureInput(FIXTURES, [COMMENTS_PROTO]);

  expect(
    alone.map((file) => {
      return file.name;
    })
  ).toEqual(['interop_bead.ts']);
  expect(contentOf(alone, 'interop_bead.ts')).toContain(' from "../../src/service/service";\n');

  for (const [importExtension, extension] of [
    ['none', ''],
    ['js', '.js'],
    ['ts', '.ts'],
  ] as const) {
    const files = typescriptTarget.generate(comments, { ...INTEROP_OPTIONS, importExtension });

    expect(
      files.map((file) => {
        return file.name;
      })
    ).toEqual(['bead/comments/v1/comments_bead.ts']);
    expect(contentOf(files, 'bead/comments/v1/comments_bead.ts')).toContain(
      ` from "../../../../../src/service/service${extension}";\n`
    );
  }
});

test('writes two services of one .proto in one file, the contract with the runtime once', () => {
  const comments = fixtureInput(FIXTURES, [COMMENTS_PROTO]);
  const [service] = comments.blueprint.services;

  if (service === undefined) {
    throw new Error('the comments fixture declares a service');
  }

  const content = contentOf(
    typescriptTarget.generate(
      {
        ...comments,
        blueprint: {
          ...comments.blueprint,
          services: [service, { ...service, serviceId: 3, serviceName: 'Other' }],
        },
      },
      DEFAULTS
    ),
    'bead/comments/v1/comments_bead.ts'
  );

  expect(content).toContain('export class CommentsServer<Data = unknown> {');
  expect(content).toContain('export class OtherServer<Data = unknown> {');
  expect(content.match(/GENERATED_CODE_SUPPORTS_VERSION_2;/gu)).toHaveLength(1);
  expect(content.match(/^\/\/ @generated/gmu)).toHaveLength(1);
});

test('writes */ as *\\/ and keeps two paragraphs', () => {
  const content = contentOf(
    typescriptTarget.generate(fixtureInput(FIXTURES, [COMMENTS_PROTO]), DEFAULTS),
    'bead/comments/v1/comments_bead.ts'
  );

  expect(content).toContain(
    '   * Holds a block\'s end, *\\/, and markup: <tag>, & and "quotes", a backslash \\ and an astral 😀. Admits a call in a session.\n'
  );
  expect(content).toContain(
    [
      ' * The procedures of `bead.comments.v1.CommentsService`: service 2, revision 3.',
      ' *',
      ' * The comments fixture: how a leading comment becomes a description, whatever it holds.',
      ' *',
      ' * A second paragraph, its lines joined by one space.',
      ' */',
    ].join('\n')
  );
});

test('puts the header above the imports', () => {
  const input = fixtureInput(MESSAGES);
  const content = contentOf(
    typescriptTarget.generate(input, DEFAULTS),
    'bead/messages/v1/messages_bead.ts'
  );
  const lines = content.split('\n');

  expect(lines.slice(0, 5)).toEqual([
    `// @generated by beadc ${beadcVersion()} from test/messages/${MESSAGES_PROTO}: bead-blueprint/1, spec ${input.blueprint.specVersion}.`,
    '// Do not edit: regenerate with beadc.',
    `// Messages: protoc-gen-es ${protocGenEsVersion()}, for @bufbuild/protobuf ${PROTOBUF_FLOOR} or later.`,
    '',
    `import type { IServiceClient, IServiceClientOptions, IServiceServer, ServiceResolvers, ServiceServerOptions } from "${DEFAULT_RUNTIME}";`,
  ]);
  expect(content).not.toContain('eslint-disable');
});

test('aliases a runtime type a class of the service takes the name of', () => {
  const blueprint = structuredClone(interop()) as unknown as {
    services: { serviceName: string }[];
  };

  (blueprint.services[0] as { serviceName: string }).serviceName = 'Service';

  const content = contentOf(
    typescriptTarget.generate(interopInput(blueprint as unknown as IBlueprint), DEFAULTS),
    'service_bead.ts'
  );

  expect(content).toContain(
    'import type { IServiceClient, IServiceClientOptions, IServiceServer, ServiceResolvers as ServiceResolvers$1, ServiceServerOptions as ServiceServerOptions$1 }'
  );
  expect(content).toContain(
    'export type ServiceResolvers = ServiceResolvers$1<typeof ServiceProcedures>;'
  );
  expect(content).toContain(
    'export type ServiceServerOptions = Exclude<ServiceServerOptions$1<typeof ServiceProcedures>[0], undefined>;'
  );
});

test("imports an external output's messages from messagesOut, at each file's depth, and names no generator of them", () => {
  const content = contentOf(
    typescriptTarget.generate(fixtureInput(MESSAGES), {
      ...DEFAULTS,
      messages: Messages.EXTERNAL,
      messagesOut: '../messages',
    }),
    'bead/messages/v1/messages_bead.ts'
  );

  expect(content).toContain(
    'import { Greeting_ReplySchema, GreetingSchema } from "../../../../messages/bead/messages/v1/messages_pb.ts";\n'
  );
  expect(content).not.toContain('// Messages:');
});

