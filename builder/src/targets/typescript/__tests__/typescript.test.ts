// a fixture's root through check, as generate reads a .proto source, the header naming each file
// by its path from builder/
const fixtureInput = (root: string, files?: readonly string[]): ITargetInput => {
  const checked = checkRoots([root], files === undefined ? {} : { files });

  expect(checked.diagnostics).toEqual([]);

  if (checked.blueprint === undefined || checked.set === undefined) {
    throw new Error(`${root}: no blueprint`);
  }

  return {
    blueprint: checked.blueprint,
    set: checked.set,
    sources: {
      proto: new Map(
        (checked.blueprint.proto?.files ?? []).map((file) => {
          return [file.path, relative(BUILDER, join(root, file.path)).split(sep).join('/')];
        })
      ),
    },
  };
};

// what an output holds: the messages, then the services
const outputOf = (input: ITargetInput, options: ITypeScriptOptions): readonly IGeneratedFile[] => {
  return [
    ...(input.set === undefined
      ? []
      : generateMessages(input.set, {
          blueprint: input.blueprint,
          importExtension: options.importExtension,
        })),
    ...typescriptTarget.generate(input, options),
  ];
};

const contentOf = (files: readonly IGeneratedFile[], name: string): string => {
  const file = files.find((each) => {
    return each.name === name;
  });

  if (file === undefined) {
    throw new Error(`${name}: not written`);
  }

  return file.content;
};

// a golden's header with today's versions: a release moves beadc's and the spec's, never a golden
const today = (text: string, specVersion: string): string => {
  const header = HEADER.exec(text);

  return header === null
    ? text
    : `// @generated by beadc ${beadcVersion()} from ${String(header[1])}: ${String(header[2])}, spec ${specVersion}.\n${text.slice(header[0].length)}`;
};

const filesUnder = (folder: string): string[] => {
  return readdirSync(folder, { recursive: true, withFileTypes: true })
    .filter((entry) => {
      return entry.isFile();
    })
    .map((entry) => {
      return relative(folder, join(entry.parentPath, entry.name)).split(sep).join('/');
    });
};

test("writes the comments fixture's and the messages fixture's goldens byte for byte, today's versions in their header", () => {
  const inputs = [fixtureInput(FIXTURES, [COMMENTS_PROTO]), fixtureInput(MESSAGES)];
  const written = inputs.flatMap((input) => {
    return outputOf(input, DEFAULTS).map((file) => {
      return { ...file, specVersion: input.blueprint.specVersion };
    });
  });

  if (process.env['BEADC_WRITE_GOLDEN'] === '1') {
    for (const file of written) {
      mkdirSync(dirname(join(GOLDEN, file.name)), { recursive: true });
      writeFileSync(join(GOLDEN, file.name), file.content);
    }
  }

  expect(
    written
      .map((file) => {
        return file.name;
      })
      .sort()
  ).toEqual(
    filesUnder(GOLDEN)
      .filter((name) => {
        return !GOLDEN_CONFIGS.has(name) && !name.startsWith(HTTP_GOLDEN);
      })
      .sort()
  );

  for (const file of written) {
    expect(file.content, file.name).toBe(
      today(readFileSync(join(GOLDEN, file.name), 'utf8'), file.specVersion)
    );
  }
});

test("writes spec/transcoding.proto's output with http: true as its goldens byte for byte: its route table, the document embedded as beadc writes it", () => {
  // * the spec's own .proto, its warnings the gateway's gates answer, no error
  const checked = checkRoots([SPEC], { files: [TRANSCODING_PROTO] });

  expect(hasError(checked.diagnostics)).toBe(false);

  if (checked.blueprint === undefined || checked.set === undefined) {
    throw new Error('spec/transcoding.proto: no blueprint');
  }

  const document = documentOf(checked.blueprint, { prefix: '/api' });
  const input: ITargetInput = {
    blueprint: checked.blueprint,
    set: checked.set,
    sources: { proto: new Map([[TRANSCODING_PROTO, '../spec/transcoding.proto']]) },
  };
  const written = outputOf(input, {
    ...DEFAULTS,
    http: {
      prefix: '/api',
      document,
      problemTypes: 'https://example.com/problems/',
      runtime: DEFAULT_HTTP_RUNTIME,
    },
  });

  if (process.env['BEADC_WRITE_GOLDEN'] === '1') {
    writeFileSync(DOCUMENT_GOLDEN, document);

    for (const file of written) {
      mkdirSync(dirname(join(GOLDEN, HTTP_GOLDEN, file.name)), { recursive: true });
      writeFileSync(join(GOLDEN, HTTP_GOLDEN, file.name), file.content);
    }
  }

  expect(document).toBe(readFileSync(DOCUMENT_GOLDEN, 'utf8'));
  expect(
    written
      .map((file) => {
        return file.name;
      })
      .sort()
  ).toEqual(filesUnder(join(GOLDEN, HTTP_GOLDEN)).sort());

  for (const file of written) {
    expect(file.content, file.name).toBe(
      today(
        readFileSync(join(GOLDEN, HTTP_GOLDEN, file.name), 'utf8'),
        checked.blueprint.specVersion
      )
    );
  }

  // * the document embedded byte for byte, which the gateway encodes once
  const table = contentOf(written, 'bead_http.ts');
  const embedded = /^export const OPENAPI_DOCUMENT = (".*");$/mu.exec(table)?.[1] ?? '""';

  expect(JSON.parse(embedded)).toBe(document);
});

test("an accepted case's output differs from the interop's by its patch alone: SPEC_VERSION_NEWER's header, NOTIFICATION_RESULT's codec", () => {
  // * an HTTP member writes no line of a service's file: a route table's, under http: true
  const accepted = blueprintCases().filter((each) => {
    return (
      !each.rule.startsWith('HTTP_') &&
      each.findings.every((finding) => {
        return RULES[finding.rule as keyof typeof RULES].severity === Severity.WARNING;
      })
    );
  });
  const lines = contentOf(
    typescriptTarget.generate(interopInput(), INTEROP_OPTIONS),
    'interop_bead.ts'
  ).split('\n');
  const differencesOf = (patched: IBlueprint): string[] => {
    const theirs = contentOf(
      typescriptTarget.generate(interopInput(patched), INTEROP_OPTIONS),
      'interop_bead.ts'
    ).split('\n');

    expect(theirs).toHaveLength(lines.length);

    return theirs.filter((line, at) => {
      return line !== lines[at];
    });
  };

  expect(
    accepted.map((each) => {
      return each.rule;
    })
  ).toEqual(['NOTIFICATION_RESULT', 'SPEC_VERSION_NEWER']);

  for (const each of accepted) {
    const differences = differencesOf(applyPatch(interop(), each.patch) as IBlueprint);

    expect(differences, each.rule).toEqual(
      each.rule === 'SPEC_VERSION_NEWER'
        ? [
            `// @generated by beadc ${beadcVersion()} from spec/interop-blueprint.json: bead-blueprint/1, spec 99.0.0.`,
          ]
        : ['    result: PAYLOAD_CODECS.raw,']
    );
  }
});

