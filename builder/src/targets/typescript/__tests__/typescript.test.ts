test("a consumer's every use of a marked declaration is reported, and the file's own uses are not", () => {
  test.setTimeout(60_000);

  const files = [
    CONSUMER,
    join(GOLDEN, 'bead/comments/v1/comments_bead.ts'),
    join(GOLDEN, 'bead/messages/v1/messages_bead.ts'),
  ];
  // ! oxlint exits 1 on what it reports: its output is read whatever its exit
  const run = spawnSync(
    process.execPath,
    [
      OXLINT,
      '--type-aware',
      '-c',
      NO_DEPRECATED,
      '--disable-nested-config',
      '-f',
      'json',
      ...files,
    ],
    { cwd: BUILDER, encoding: 'utf8' }
  );
  const report = JSON.parse(run.stdout.slice(run.stdout.indexOf('{'))) as {
    diagnostics: readonly {
      filename: string;
      labels?: readonly { span: { line: number } }[];
      message: string;
    }[];
    number_of_files: number;
  };
  // * the line under each that says what it is reported, and no other line, the goldens' none
  const expected = readFileSync(CONSUMER, 'utf8')
    .split('\n')
    .flatMap((line, at) => {
      const reported = /^ *\/\/ reported: (.+)$/u.exec(line);

      return reported === null
        ? []
        : [`test/consumer/use-deprecated.ts:${String(at + 2)}: ${String(reported[1])}`];
    });

  expect(report.number_of_files).toBe(files.length);
  expect(expected.length).toBeGreaterThan(0);
  expect(
    report.diagnostics.map(({ filename, labels, message }) => {
      return `${filename.replaceAll('\\', '/')}:${String(labels?.[0]?.span.line)}: ${message}`;
    })
  ).toEqual(expected);
});
