// ── protoc ────────────────────────────────────────────────────────────────────

// The C# messages a project's `proto` bindings name, written by protoc's C# generator, the stock one,
// from buf's set alone (`--descriptor_set_in`), never compiling a `.proto` (decision 0022): the files
// that declare them and every file of the project they import, public; then `bead/options.proto`,
// where they import it, in a run of its own with `internal_access`, so each project keeps its copy
// to itself. Both runs take `base_namespace=`, protoc's own option, so each file lands in its
// namespace's folder, `Bead/Messages/V1/Messages.cs`, and two files of one name in two packages
// never meet.
//
// protoc is held to one pin, `builder/protoc.json`: its version, the oldest Google.Protobuf its code
// runs on, and each archive's sha256, which `tools/fetch-protoc.mjs` and CI read. beadc runs the
// protoc `BEADC_PROTOC` names, or `protoc` on the path, and refuses one of another version, since
// another writes other code; only `generate` looks for it, and only when it writes a message.

// dependencies

import { type ExecSyncOptionsWithStringEncoding, execFileSync, execSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative, sep } from 'node:path';

import { fromBinary } from '@bufbuild/protobuf';
import { FileDescriptorSetSchema } from '@bufbuild/protobuf/wkt';

import { InputError } from './diagnostics.ts';
import type { IBlueprint } from './model/blueprint.ts';
import { OPTIONS_FILE } from './roots.ts';
import { pascalOf } from './targets/names.ts';
import type { IGeneratedFile } from './targets/target.ts';

// types

/** The pin, `builder/protoc.json`: the one protoc beadc runs, and what its code needs. */
export interface IProtocPin {
  readonly version: string;
  /** The oldest Google.Protobuf the C# that protoc writes runs on: the runtime its release pairs. */
  readonly googleProtobuf: string;
  /** Each release archive's sha256, by its platform's name in the archive's: `win64`, `linux-x86_64`. */
  readonly sha256: Readonly<Record<string, string>>;
}

/** The protoc beadc found: where, and the version it says it is. */
export interface IFoundProtoc {
  readonly path: string;
  readonly version: string;
}

// constants

/** What a `.cs` file protoc's C# generator wrote opens with: no mark of beadc's alone. */
export const PROTOC_CSHARP_HEADER =
  '// <auto-generated>\n//     Generated by the protocol buffer compiler.  DO NOT EDIT!\n';

/** The line of that header that names the file it was written from, by its import path. */
export const PROTOC_CSHARP_SOURCE = /^\/\/ {5}source: (.+)$/mu;

// the files protoc writes nothing for: Google.Protobuf holds the well-known types
const WELL_KNOWN = 'google/protobuf/';

// the pin, beside this module's folder
const PIN = new URL('../protoc.json', import.meta.url);

// what the fetch prints its path under
const FETCH = 'node builder/tools/fetch-protoc.mjs';

// a script protoc stands behind on Windows, which runs through its shell alone
const SCRIPT = /\.(?:bat|cmd)$/iu;

// helpers

let pin: IProtocPin | undefined;

// the protoc beadc runs: BEADC_PROTOC's, or the path's
const protocPath = (): string => {
  const named = process.env['BEADC_PROTOC'];

  return named === undefined || named === '' ? 'protoc' : named;
};

// runs protoc over `args`, its output as text; a script through the shell, each part quoted
const run = (path: string, args: readonly string[]): string => {
  const options: ExecSyncOptionsWithStringEncoding = {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
    windowsHide: true,
  };

  if (process.platform === 'win32' && SCRIPT.test(path)) {
    return execSync(
      [path, ...args]
        .map((part) => {
          return `"${part}"`;
        })
        .join(' '),
      options
    );
  }

  return execFileSync(path, args, options);
};

// every file under `folder`, by its path from it, with slashes
const filesUnder = (folder: string): string[] => {
  return readdirSync(folder, { recursive: true, withFileTypes: true })
    .filter((entry) => {
      return entry.isFile();
    })
    .map((entry) => {
      return relative(folder, join(entry.parentPath, entry.name)).split(sep).join('/');
    })
    .sort();
};

// definition

/** The pin, read from `builder/protoc.json` once. */
export const protocPin = (): IProtocPin => {
  pin ??= Object.freeze(JSON.parse(readFileSync(PIN, 'utf8')) as IProtocPin);

  return pin;
};

/**
 * The path protoc's C# generator gives the file of `source`, a `.proto` by its import path, in
 * `namespace`, under `base_namespace=`: its namespace's folder, its parts by `/`, then its base name
 * in Pascal case and `.cs`, `Bead/Messages/V1/Messages.cs`.
 */
export const csharpPathOf = (source: string, namespace: string): string => {
  const base = pascalOf(source.slice(source.lastIndexOf('/') + 1).replace(/\.proto$/u, ''));

  return namespace === '' ? `${base}.cs` : `${namespace.split('.').join('/')}/${base}.cs`;
};

/** The protoc beadc finds, `BEADC_PROTOC` or the path's, and its version; none when none runs. */
export const findProtoc = (): IFoundProtoc | undefined => {
  const path = protocPath();

  try {
    const said = run(path, ['--version']).trim();

    return { path, version: said.replace(/^libprotoc /u, '') };
  } catch {
    return undefined;
  }
};

/**
 * The protoc beadc runs, at its pin's version. Throws an {@link InputError} with the fix for none,
 * or for one of another version, which writes other code.
 */
export const requireProtoc = (): IFoundProtoc => {
  const found = findProtoc();
  const { version } = protocPin();

  if (found === undefined) {
    throw new InputError(
      `no protoc at ${protocPath()}, which writes the C# messages: fetch protoc ${version}, its pin, with ${FETCH} and name it by BEADC_PROTOC, or set the output's messages to external`
    );
  }

  if (found.version !== version) {
    throw new InputError(
      `protoc ${found.version} at ${found.path}, where beadc is pinned to protoc ${version} (builder/protoc.json), whose C# another writes otherwise: fetch it with ${FETCH} and name it by BEADC_PROTOC`
    );
  }

  return found;
};

/**
 * The C# files of the messages `blueprint` binds, from `set`, buf's FileDescriptorSet of its
 * `.proto` source, each at its namespace's folder as protoc writes it: none, and no protoc looked
 * for, when it binds none of a file of its own. Throws an {@link InputError} for no protoc, one off
 * its pin, or protoc's own refusal, in its words.
 */
export const generateCSharpMessages = (
  set: Uint8Array,
  options: { readonly blueprint: IBlueprint }
): readonly IGeneratedFile[] => {
  const descriptors = fromBinary(FileDescriptorSetSchema, set);
  const dependencies = new Map(
    descriptors.file.map((file) => {
      return [file.name, file.dependency];
    })
  );
  const wanted = new Set<string>();
  const want = (file: string): void => {
    if (file.startsWith(WELL_KNOWN) || wanted.has(file)) {
      return;
    }

    wanted.add(file);

    for (const dependency of dependencies.get(file) ?? []) {
      want(dependency);
    }
  };

  for (const message of options.blueprint.proto?.messages ?? []) {
    want(message.file);
  }

  if (wanted.size === 0) {
    return [];
  }

  const protoc = requireProtoc();
  const folder = mkdtempSync(join(tmpdir(), 'beadc-protoc-'));
  // in the set's order, which is buf's, Bead's options in a run of their own
  const ordered = descriptors.file
    .map((file) => {
      return file.name;
    })
    .filter((name) => {
      return wanted.has(name);
    });
  const runs = [
    {
      out: join(folder, 'public'),
      option: 'base_namespace=',
      files: ordered.filter((name) => {
        return name !== OPTIONS_FILE;
      }),
    },
    {
      out: join(folder, 'internal'),
      option: 'internal_access,base_namespace=',
      files: ordered.filter((name) => {
        return name === OPTIONS_FILE;
      }),
    },
  ];

  try {
    const setFile = join(folder, 'set.binpb');

    writeFileSync(setFile, set);

    return runs.flatMap((each) => {
      if (each.files.length === 0) {
        return [];
      }

      mkdirSync(each.out, { recursive: true });

      try {
        run(protoc.path, [
          `--descriptor_set_in=${setFile}`,
          `--csharp_out=${each.out}`,
          `--csharp_opt=${each.option}`,
          ...each.files,
        ]);
      } catch (error) {
        const { stderr } = error as { stderr?: unknown };

        throw new InputError(
          `protoc: ${typeof stderr === 'string' && stderr.trim() !== '' ? stderr.trim() : (error as Error).message}`
        );
      }

      return filesUnder(each.out).map((name) => {
        return {
          name,
          content: readFileSync(join(each.out, ...name.split('/')), 'utf8').replaceAll(
            '\r\n',
            '\n'
          ),
        };
      });
    });
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
};
