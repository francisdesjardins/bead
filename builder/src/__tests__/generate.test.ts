test("takes out nothing unless clean is set, and under it a foreign protoc-gen-es file alone, named, a person's _bead.ts and a gRPC stub kept", () => {
  const yaml = [
    'version: 1',
    'source:',
    '  proto: [proto]',
    'outputs:',
    '  - language: typescript',
    '    out: gen',
    '',
  ].join('\n');
  // a protoc-gen-es file of a source the project no longer has, a person's own _bead.ts and a
  // stub another plugin wrote
  const foreign = {
    'other/v1/other_pb.ts':
      '// @generated by protoc-gen-es v2.16.0 with parameter "target=ts"\n// @generated from file other/v1/other.proto (package other.v1, syntax proto3)\n/* eslint-disable */\n\nexport {};\n',
    'legacy_bead.ts':
      '// A resolver module of the project, named as beadc names its files.\nexport {};\n',
    'other/v1/other_grpc_pb.ts': '// GENERATED CODE -- DO NOT EDIT!\nexport {};\n',
  };
  const projectWith = (text: string): string => {
    const folder = projectOf(text, { proto: MESSAGES });

    generate(folder);

    for (const [path, content] of Object.entries(foreign)) {
      mkdirSync(dirname(join(folder, 'gen', path)), { recursive: true });
      writeFileSync(join(folder, 'gen', path), content);
    }

    return folder;
  };
  const left = (folder: string): string[] => {
    return Object.keys(foreign).filter((path) => {
      return existsSync(join(folder, 'gen', path));
    });
  };

  // * buf's default, protoc's only behaviour: nothing taken out, and nothing named
  const kept = projectWith(yaml);

  expect(findingsOf(kept)).toEqual([]);
  expect(
    spawnSync(process.execPath, [CLI, 'generate'], { cwd: kept, encoding: 'utf8' }).stdout
  ).toBe('');
  expect(left(kept)).toEqual(Object.keys(foreign));

  // under clean: the protoc-gen-es file alone, by its header, named as it goes
  const cleaned = projectWith(`${yaml}clean: true\n`);

  expect(findingsOf(cleaned)).toEqual([
    'gen/other/v1/other_pb.ts: other/v1/other.proto no longer gives it: beadc generate takes it out, under clean',
  ]);
  expect(
    spawnSync(process.execPath, [CLI, 'generate'], { cwd: cleaned, encoding: 'utf8' }).stdout
  ).toBe(
    'beadc: generate takes out gen/other/v1/other_pb.ts: other/v1/other.proto no longer gives it\n'
  );
  expect(left(cleaned)).toEqual(['legacy_bead.ts', 'other/v1/other_grpc_pb.ts']);
});

